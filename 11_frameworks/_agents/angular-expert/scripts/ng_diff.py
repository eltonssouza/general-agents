# -*- coding: utf-8 -*-
"""
ng_diff.py - difference map between the 5 Angular Overview captures (NG18..NG22).

Usage:
  python -I scripts/ng_diff.py diff --from 18 --to 22 [--group feature] [--json] [--raw --src DIR]
  python -I scripts/ng_diff.py matrix [--group G]       # concept x version (PDF pages)
  python -I scripts/ng_diff.py concept ID               # one concept across all versions
  python -I scripts/ng_diff.py meta                     # pages, footer, stamp, useless pages per version

Single source: scripts/ng_index.json (generated by ng_build_index.py) and scripts/ng_changes.json (curated).
"--raw --src DIR" compares the original .txt files by word n-grams (read-only; no text copied to files).
Golden rule: ABSENCE in a capture is NOT proof of removal in the framework. No network; nothing from the target is executed.
Groups: framing, feature, tool, stability, scale, community, meta (the old Portuguese names are also accepted).
"""
import argparse
import json
import os
import re
import sys

for _s in (sys.stdout, sys.stderr):
    try:
        _s.reconfigure(encoding="utf-8")
    except Exception:
        pass

HERE = os.path.dirname(os.path.abspath(__file__))
VERSIONS = [18, 19, 20, 21, 22]
# Portuguese group names accepted as input -> English names used in the index
GROUP_ALIAS = {"enquadramento": "framing", "recurso": "feature", "ferramenta": "tool", "estabilidade": "stability",
               "escala": "scale", "comunidade": "community"}
WARNING = ("WARNING: the absence of a concept in an Overview capture does NOT mean it was removed or does not exist "
           "in the version; the page is only an overview (doc-capture).")


def group_name(g):
    return GROUP_ALIAS.get(g, g) if g else g


def load():
    idx = json.load(open(os.path.join(HERE, "ng_index.json"), encoding="utf-8"))
    chg = json.load(open(os.path.join(HERE, "ng_changes.json"), encoding="utf-8"))
    return idx, chg["changes"]


def cite(v, pages):
    return f"NG{v} p." + ",".join(str(p) for p in pages)


def concept_diff(idx, a, b, group=None):
    out = {"only_from": [], "only_to": [], "in_both": [], "in_neither": []}
    for c in idx["concepts"]:
        if group and c["group"] != group:
            continue
        pa, pb = c["pages"].get(str(a)), c["pages"].get(str(b))
        item = {"id": c["id"], "label": c["label"], "group": c["group"],
                "from": cite(a, pa) if pa else None, "to": cite(b, pb) if pb else None}
        if pa and pb:
            out["in_both"].append(item)
        elif pa:
            out["only_from"].append(item)
        elif pb:
            out["only_to"].append(item)
        else:
            out["in_neither"].append(item)
    return out


def curated(chgs, a, b):
    lo, hi = (a, b) if a <= b else (b, a)
    return [c for c in chgs if lo < c["step"] <= hi]


def tokens(path):
    sys.path.insert(0, HERE)
    import ng_build_index as bi
    pg = bi.load_pages(path)
    lines = []
    for n in sorted(pg):
        for ln in pg[n].splitlines():
            t = ln.strip()
            if t and not any(r.match(t) for r in bi.BOILER_RE):
                lines.append(t)
    return re.findall(r"[\w@.+'-]+", bi.norm("\n".join(lines)))


def runs(A, B, n=4, maxw=40):
    sb = {tuple(B[i:i + n]) for i in range(len(B) - n + 1)}
    cov = [False] * len(A)
    for i in range(len(A) - n + 1):
        if tuple(A[i:i + n]) in sb:
            for k in range(i, i + n):
                cov[k] = True
    res, cur = [], []
    for t, c in zip(A, cov):
        if not c:
            cur.append(t)
        else:
            if cur:
                res.append(cur)
            cur = []
    if cur:
        res.append(cur)
    seen, out = set(), []
    for r in res:
        s = " ".join(r[:maxw]) + (" ..." if len(r) > maxw else "")
        if s not in seen:
            seen.add(s)
            out.append(s)
    return out


def cmd_diff(a):
    idx, chgs = load()
    f, t = a.frm, a.to
    for v in (f, t):
        if v not in VERSIONS:
            sys.exit(f"version {v} is not in {VERSIONS}")
    cd = concept_diff(idx, f, t, group_name(a.group))
    cur = curated(chgs, f, t)
    if a.json:
        print(json.dumps({"from": f, "to": t, "warning": WARNING, "concepts": cd,
                          "curated_changes": cur}, ensure_ascii=False, indent=1))
        return
    print(f"DIFFERENCE MAP NG{f} -> NG{t}  (source: Overview captures; pages = PDF pages)")
    print(WARNING)
    mf, mt = idx["meta"][str(f)], idx["meta"][str(t)]
    print(f"\n[meta] NG{f}: {mf['pages']} pages, footer {mf['footer_years']}, stamp {mf['build_stamp'] or '-'} | "
          f"NG{t}: {mt['pages']} pages, footer {mt['footer_years']}, stamp {mt['build_stamp'] or '-'}")
    print(f"\n== A. Concepts cited in NG{f} and NOT detected in NG{t} ({len(cd['only_from'])}) [from source; not 'removed']")
    for i in cd["only_from"]:
        print(f"  - {i['label']}  ({i['from']})")
    print(f"\n== B. Concepts detected in NG{t} and NOT in NG{f} ({len(cd['only_to'])}) [from source]")
    for i in cd["only_to"]:
        print(f"  - {i['label']}  ({i['to']})")
    print(f"\n== C. Concepts present in both ({len(cd['in_both'])}) [from source]")
    for i in cd["in_both"]:
        print(f"  = {i['label']}  ({i['from']} | {i['to']})")
    if f == t:
        print("\n(same versions)")
        return
    print(f"\n== D. Wording/layout/footer/capture changes, steps {f}->{t} [from source; curated patterns] ({len(cur)})")
    for c in cur:
        print(f"  [{c['kind']}] (NG{c['step']}) {c['summary']}  <{'; '.join(c['cites'])}>")
    if not cur:
        print("  (none recorded)")
    if a.raw:
        if not a.src:
            sys.exit("--raw requires --src DIR with the .txt files")
        A = tokens(os.path.join(a.src, f"Angular-{f}-Overview.txt"))
        B = tokens(os.path.join(a.src, f"Angular-{t}-Overview.txt"))
        print(f"\n== E. Raw 4-gram comparison (fragments only in NG{f}, then only in NG{t}; line-break noise possible)")
        print(f"  -- only in NG{f}:")
        for r in runs(A, B)[:40]:
            print("    ", r)
        print(f"  -- only in NG{t}:")
        for r in runs(B, A)[:40]:
            print("    ", r)
    print("\n[inference] Items in A/B indicate a TEXT difference between captures, not a difference in framework features.")


def cmd_matrix(a):
    idx, _ = load()
    g = group_name(a.group)
    print("concept".ljust(34) + " ".join(f"NG{v}".ljust(7) for v in VERSIONS))
    for c in idx["concepts"]:
        if g and c["group"] != g:
            continue
        row = " ".join((",".join(map(str, c["pages"].get(str(v), []))) or "-").ljust(7) for v in VERSIONS)
        print(c["id"].ljust(34) + row)
    print("(cells = PDF pages where the pattern appears; '-' = not detected in the capture)")
    print(WARNING)


def cmd_concept(a):
    idx, chgs = load()
    hit = [c for c in idx["concepts"] if a.id in c["id"] or a.id.lower() in c["label"].lower()]
    if not hit:
        print(f"NOT COVERED: concept '{a.id}' is not in the Overviews' concept index.")
        return
    for c in hit:
        print(f"{c['id']} [{c['group']}] {c['label']}")
        for v in VERSIONS:
            pg = c["pages"].get(str(v))
            print(f"  NG{v}: " + (f"p.{','.join(map(str, pg))}" if pg else "not detected in the capture"))
        print(f"  note: {c['note']}")


def cmd_meta(a):
    idx, _ = load()
    for v in VERSIONS:
        m = idx["meta"][str(v)]
        useless = [p for p, k in m["page_class"].items() if k == "navigation-or-footer-only"]
        print(f"NG{v}: {m['pages']} pages | label {m['nav_version_label']} | footer {m['footer_years']} | "
              f"stamp {m['build_stamp'] or '-'} | navigation/footer-only pages: {useless or 'none'} | "
              f"cookie banner on {len(m['cookie_banner_pages'])} pages")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sp = ap.add_subparsers(dest="cmd", required=True)
    d = sp.add_parser("diff")
    d.add_argument("--from", dest="frm", type=int, required=True)
    d.add_argument("--to", type=int, required=True)
    d.add_argument("--group")
    d.add_argument("--json", action="store_true")
    d.add_argument("--raw", action="store_true")
    d.add_argument("--src")
    d.set_defaults(fn=cmd_diff)
    m = sp.add_parser("matrix")
    m.add_argument("--group")
    m.set_defaults(fn=cmd_matrix)
    c = sp.add_parser("concept")
    c.add_argument("id")
    c.set_defaults(fn=cmd_concept)
    e = sp.add_parser("meta")
    e.set_defaults(fn=cmd_meta)
    a = ap.parse_args()
    a.fn(a)


if __name__ == "__main__":
    main()
