# -*- coding: utf-8 -*-
"""
verify_citations.py - audits the citations of the graph-databases-neo4j-expert package against the text extracted from the PDFs.

Usage (from the package root):
  python -I tests/verify_citations.py --text NEO4J.txt [--text-start NEO_START.txt] [-v]
  python -I tests/verify_citations.py --text NEO4J.txt --refs      # also scans references/, agents/, AGENTS.md etc.

The texts ("=== PAGE N ===" markers, N = PDF page) are generated by tests/extract_pages.py from the PDFs
(the PDFs are not part of the package).

Checks:
  POSITIVE: all 'terms' appear (case-insensitive, whitespace and end-of-line hyphenation normalized) in the
            cited 'pages' (each term may be on any of the listed pages).
  NEGATIVE: none of the 'terms' appears on ANY page ('re:...' terms are regexes).
  --refs  : every '(NEO4J p.N...)' and '(NEO_START p.N...)' citation in the package files must be within the PDF range
            (NEO4J 1-238; NEO_START 1-4) and must not use the printed numbering by mistake (checks that the range
            does not exceed the last page).
Read-only, no network. Exit code 0 if everything passed, 1 otherwise.
"""
import argparse
import json
import os
import re
import sys
import unicodedata

for _s in (sys.stdout, sys.stderr):
    try:
        _s.reconfigure(encoding="utf-8")
    except Exception:
        pass

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def normtext(s):
    s = unicodedata.normalize("NFKC", s)
    s = s.replace("‐ ", "").replace("‐\n", "").replace("‐", "-").replace("‑", "-")
    s = s.replace("’", "'").replace("‘", "'").replace("“", '"').replace("”", '"').replace("�", "'")
    return re.sub(r"\s+", " ", s)


def load_pages(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        raw = f.read()
    parts = re.split(r"=== PAGE (\d+) ===", raw)
    return {int(parts[i]): normtext(parts[i + 1]) for i in range(1, len(parts), 2)}


def has(text, term):
    term = normtext(term)
    if term.startswith("re:"):
        return re.search(term[3:], text, re.IGNORECASE) is not None
    return term.lower() in text.lower()


def parse_pages(spec):
    pages = []
    for part in re.split(r"[;,]", spec):
        m = re.search(r"(\d+)(?:\s*[-–]\s*(\d+))?", part)
        if m:
            a = int(m.group(1))
            b = int(m.group(2) or a)
            pages.extend(range(a, b + 1))
    return pages


def scan_refs(maxp):
    bad, total = [], 0
    files = []
    for base in ("references", "agents", ".github", "scripts"):
        for dp, _, fns in os.walk(os.path.join(ROOT, base)):
            for fn in fns:
                if fn.endswith((".md", ".py", ".json")):
                    files.append(os.path.join(dp, fn))
    for fn in ("README.md", "AGENTS.md"):
        files.append(os.path.join(ROOT, fn))
    cite = re.compile(r"\b(NEO4J|NEO_START) p\.([^)`]*)")
    for f in files:
        if not os.path.exists(f):
            continue
        with open(f, encoding="utf-8") as fh:
            for ln, line in enumerate(fh, 1):
                for m in cite.finditer(line):
                    for p in parse_pages(m.group(2)):
                        total += 1
                        lim = maxp.get(m.group(1), 238)
                        if p < 1 or p > lim:
                            bad.append("%s:%d: %s p.%d out of range 1-%d" % (os.path.relpath(f, ROOT), ln, m.group(1), p, lim))
    return total, bad


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--text", required=True, help="NEO4J.txt")
    ap.add_argument("--text-start", help="NEO_START.txt")
    ap.add_argument("--checks", default=os.path.join(ROOT, "tests", "citation-checks.json"))
    ap.add_argument("--refs", action="store_true")
    ap.add_argument("-v", "--verbose", action="store_true")
    a = ap.parse_args()

    srcs = {"NEO4J": load_pages(a.text)}
    if a.text_start:
        srcs["NEO_START"] = load_pages(a.text_start)
    with open(a.checks, encoding="utf-8") as f:
        checks = json.load(f)

    fails, skipped = [], 0
    for c in checks["positive"]:
        pages = srcs.get(c.get("src", "NEO4J"))
        if pages is None:
            skipped += 1
            continue
        blob = " ".join(pages.get(p, "") for p in c["pages"])
        missing = [t for t in c["terms"] if not has(blob, t)]
        ok = not missing
        if a.verbose or not ok:
            print(("OK   " if ok else "FAIL "), c["id"], c.get("src", "NEO4J"), "p.", c["pages"], "-", c["claim"],
                  "" if ok else "| missing: %s" % missing)
        if not ok:
            fails.append(c["id"])
    for c in checks["negative"]:
        pages = srcs.get(c.get("src", "NEO4J"))
        if pages is None:
            skipped += 1
            continue
        found = []
        for n, txt in pages.items():
            for t in c["terms"]:
                if has(txt, t):
                    found.append((n, t))
        ok = not found
        if a.verbose or not ok:
            print(("OK   " if ok else "FAIL "), c["id"], "(negative) -", c["claim"],
                  "" if ok else "| found at %s" % found[:5])
        if not ok:
            fails.append(c["id"])

    if a.refs:
        total, bad = scan_refs({"NEO4J": max(srcs["NEO4J"]), "NEO_START": 4})
        print("Page citations scanned: %d; out of range: %d" % (total, len(bad)))
        for b in bad[:30]:
            print("FAIL", b)
        if bad:
            fails.append("refs-faixa")
    npos, nneg = len(checks["positive"]), len(checks["negative"])
    print("Summary: %d positive, %d negative, %d failures%s" % (npos, nneg, len(fails),
          (", %d skipped (source missing)" % skipped) if skipped else ""))
    if fails:
        print("Failures:", ", ".join(fails))
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
