# ---------------------------------------------------------------- normalization (identical to build_book_index.py)
STOP_EN = set("""
a about above after again against all also am an and any are as at be because been before being below between both
but by can could did do does doing down during each few for from further had has have having he her here hers him his
how i if in into is it its itself just me more most my no nor not now of off on once only or other our out over own
same she should so some such than that the their theirs them then there these they this those through to too under
until up very was we were what when where which while who whom why will with would you your yours may might must shall
us one two per via vs etc eg ie
""".split())
# generic query words (pt/en) that do not identify the topic
STOP_Q = set("""
o a os as um uma uns umas de do da dos das e em no na nos nas para por com sem sobre como qual quais que quem onde
quando se ou ao aos pelo pela livro livros book sre google diz dizer disse traz trazer trata tratar tema topico
existe existem tem ter ha pagina paginas me fale explique explica mostre mostra conta sao eh
say says said tell explain describe mention mentions cover covers discuss discusses show
quanto quanta quantos quantas quantidade
""".split())


def norm(s):
    s = unicodedata.normalize("NFKC", str(s)).lower()
    s = unicodedata.normalize("NFD", s)
    return "".join(c for c in s if unicodedata.category(c) != "Mn")


TOK = re.compile(r"[a-z0-9][a-z0-9+_\-]*")
NPLUS = re.compile(r"(?<![a-z0-9])n\s*\+\s*(\d)")


def prep(text):
    """norm + 'N + 0' / 'N+0' become the same token 'n+0' (identical to build_book_index.py and build_ref_index.py)"""
    return NPLUS.sub(r"n+\1", norm(text))


def variants(w):
    """simple en/pt inflections (plural, -ed, -d, -ing, -ies/-y) of the word; used on both sides of the search"""
    out = {w, w + "s", w + "es"}
    if w.endswith("s"):
        out.add(w[:-1])
    if w.endswith("es"):
        out.add(w[:-2])
    if len(w) < 4:
        return out
    out |= {w + "d", w + "ed", w + "ing"}
    if w.endswith("e"):
        out.add(w[:-1] + "ing")
    if w.endswith("ies") and len(w) > 4:
        out.add(w[:-3] + "y")
    if w.endswith("ied") and len(w) > 4:
        out.add(w[:-3] + "y")
    for suf in ("ed", "d", "ing", "ly"):
        if w.endswith(suf) and len(w) - len(suf) >= 4:
            out.add(w[:-len(suf)])
            if suf == "ing":
                out.add(w[:-3] + "e")
    return out


def simple_tokens(text):
    """tokens as in the indexer (without expanding parts), without English stopwords and without long digit-only tokens"""
    out = []
    for t in TOK.findall(prep(text)):
        t = t.strip("-_+") if not t.endswith("++") else t.rstrip("-_")
        if len(t) < 2 or t in STOP_EN:
            continue
        if t.isdigit() and len(t) > 4:
            continue
        out.append(t)
    return out


def units_of(query):
    """meaningful units of the query (without query stopwords), in order, without repetition"""
    seen, out = set(), []
    for t in simple_tokens(query):
        if t in STOP_Q or t in seen:
            continue
        seen.add(t)
        out.append(t)
    return out


def word_in(a, b):
    """a occurs in b as a sequence of whole words"""
    if not a:
        return False
    return re.search(r"(?<![a-z0-9])" + re.escape(a) + r"(?![a-z0-9])", b) is not None


