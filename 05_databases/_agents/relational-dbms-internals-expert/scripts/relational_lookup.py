# -*- coding: utf-8 -*-
"""
relational_lookup.py - deterministic THREE-LEVEL lookup over what the package sources cover.

Levels (exit code):
  COVERED        (0)  the queried term (whole phrase, delimited by non-alphanumerics; simple plural tolerated) is the SUBJECT of a
                      SUMMARY excerpt in references/*.md: it appears in the title of a body section or at the start of the excerpt
                      (the subject: up to the first ':'), in text of a [from source]/[inference]/[derived]/[DATED] section
                      (index ref_terms.json, class "b", generated by scripts/build_ref_index.py from the contents of the references).
                      NO substring of file names, topic ids/titles/keywords: what decides is the text of the summary. Curated topics
                      only show up in the output to display the pages and the summary of the excerpts that matched (linked by the pages
                      cited in the excerpt). A PASSING mention (in the middle of a sentence about another subject) is not enough:
                      it becomes POINTER ONLY, and the excerpts with the mention are shown for the agent to check.
  POINTER ONLY   (3)  the term is only mentioned in passing in the summaries, or appears only in pointer/map text (INDEX.md, navigation
                      maps, metadata blocks, "pointer only" lines), in a curated 'ponteiro' topic, or only in the SOURCE term index
                      (source_terms.json: textual occurrence on the PDF pages, no semantics). The package has NO summary: the agent
                      must say there is content on pages X and suggest reading it. Never equivalent to "the book does not cover it".
  NOT COVERED    (1)  (a) a term from a CURATED LIST of things outside the sources (field not_in_book), or
                      (b) no occurrence in the term index of any source (the sources are in English: try synonyms;
                      absence from the term index does NOT prove the sources do not cover the topic, only that the term does not appear).
  (exit 2: incorrect usage, no term.)

PT/EN equivalences ("aliases" field of relational_index.json): the summaries are in Portuguese and the sources and questions are in English; an
alias group lists equivalent terms VALIDATED against the pages (tests/citation-checks.json proves the English term on the page and the test proves the
Portuguese term in the summary). The lookup also searches the equivalent terms (phrase equality, plural tolerated) and says which equivalence it used.
Terms with (*), such as count(*), require the excerpt to carry the literal call (otherwise "count" of "pin count" would match).
Origin: ref_terms.json (summaries; build_ref_index.py), relational_index.json (page map of the topics, checked against the PDFs by
tests/verify_citations.py) and source_terms.json (inverted index term -> source pages; build_term_index.py).
Convention: all pages are PDF pages; printed ARCH = N+140; printed PG16 = N-38.

Usage:
  python -I relational_lookup.py "<term>"            (or --topic "<term>")
  python -I relational_lookup.py --list
  python -I relational_lookup.py "<term>" --json     (structured output)
No network; read-only. If the references change without regenerating ref_terms.json, it warns on stderr (run build_ref_index.py).
"""
