"""
sre_lookup.py - deterministic lookup of the Google SRE Book (2016), with pages, in THREE LEVELS.
Reads sre_index.json (summarized topics, curated list of things outside the book) and book_term_index.json (inverted index
term -> PDF pages, generated from the book's own text by build_book_index.py). Read-only, offline.

Output levels (return code):
  COVERED          (rc 0)  ONLY when the term appears, as a whole word, in the BODY of a references summary
                           (references/*.md, which cites a page), according to ref_term_index.json (generated by build_ref_index.py).
                           File name, title, topic keyword, pointer list and "the book does not say" note are NOT enough.
  POINTER ONLY     (rc 3)  no topic, but the term EXISTS in the book (pages X): say the book covers/mentions
                           the topic on those pages and that the package does not summarize it. Do not invent content.
  NOT COVERED      (rc 1)  (a) term from the curated list of things OUTSIDE the book (burn rate, circuit breaker, DORA...): only here can
                           you say 'the book does not cover this'; or (b) 'not found in the index' (whole word, with simple inflections
                           and pt/en synonyms): does NOT prove absence; check spelling/plural/inflection/English (--pages) and read the
                           page before claiming the book lacks the topic.

Usage:
  python -I sre_lookup.py "error budget"       search by term/topic name (several words are joined)
  python -I sre_lookup.py --list               list the topics
  python -I sre_lookup.py --topic toil         show a topic by key
  python -I sre_lookup.py --pages "etcd"       book pages with the term (book index)
  python -I sre_lookup.py --check              consistency of topic keywords (rc 1 on failure)
Terms with more than one sense in the book (flow, shadow, dns, config; ambiguous_terms key of sre_index.json) get an
ALERT block with the senses and pages.
Pages = PDF (printed = N-12).
Portuguese and English query terms are both recognized (the indexes and synonyms are bilingual).
"""
