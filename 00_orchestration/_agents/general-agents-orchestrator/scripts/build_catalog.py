# -*- coding: utf-8 -*-
"""
build_catalog.py - generates the catalog of specialist agents from the real files.

Reads the frontmatter of <ROOT>/NN_*/_agents/<name>/agents/<name>.md (NN from 01 to 99; the
00_orchestration folder, where the orchestrator lives, is ignored) and writes:
  - "kind": "role" for agents of a domain whose name ends in "_roles" (e.g. 12_product_and_leadership_roles:
    they produce deliverables, with no bibliographic source, [practice] label); "specialist" for the rest
    (they answer from their own sources, with page citations).
  - "model": tier and models of the policy (scripts/models.json) and the alias written in the frontmatter
    (applied by apply_models.py); route.py --show shows both.
  scripts/catalog.json      (consumed by route.py)
  references/catalogo.md    (human-readable table per domain)

Usage (from the package root; always with python -I):
  python -I scripts/build_catalog.py                 # regenerate both files
  python -I scripts/build_catalog.py --check         # compare only; exit 1 if the catalog is stale
  python -I scripts/build_catalog.py --root PATH     # root containing the 01_* ... NN_* folders

Default --root: three levels above the package (general-agents/).
Read-only on the repository; no network; stdlib only.
Exit: 0 = ok; 1 = stale catalog (--check); 2 = read/format error.
"""
import argparse
import json
import os
import re
import sys

for _s in (sys.stdout, sys.stderr):
    try:
        _s.reconfigure(encoding="utf-8")
    except Exception:
        pass

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(HERE)
DEFAULT_ROOT = os.path.normpath(os.path.join(PKG, "..", "..", ".."))
CATALOG = os.path.join(HERE, "catalog.json")
CATALOG_MD = os.path.join(PKG, "references", "catalogo.md")
MODELS = os.path.join(HERE, "models.json")
DOMAIN_RE = re.compile(r"^(\d{2})_[a-z0-9_]+$")
ROLE_SUFFIX = "_roles"  # domain of role agents


def unquote(v):
    v = v.strip()
    if len(v) >= 2 and v[0] == v[-1] == "'":
        return v[1:-1].replace("''", "'")
    if len(v) >= 2 and v[0] == v[-1] == '"':
        return v[1:-1].replace('\\"', '"')
    return v


def frontmatter(path):
    with open(path, "r", encoding="utf-8") as f:
        text = f.read()
    m = re.match(r"^---\r?\n(.*?)\r?\n---\r?\n(.*)$", text, re.S)
    if not m:
        raise ValueError("no YAML frontmatter: " + path)
    meta = {}
    for line in m.group(1).splitlines():
        kv = re.match(r"^([A-Za-z][\w-]*):\s*(.*)$", line)
        if kv:
            meta[kv.group(1)] = unquote(kv.group(2))
    return meta, m.group(2)


def model_info(policy, kind, name, front):
    tier = policy["exceptions"].get(name) or policy["default"][kind]
    spec = policy["tiers"][tier]
    return {"tier": tier, "claude": front, "claude_policy": spec["claude"], "openai": spec["openai"]}


def scan(root):
    with open(MODELS, encoding="utf-8") as f:
        policy = json.load(f)
    agents = []
    for dom in sorted(os.listdir(root)):
        dm = DOMAIN_RE.match(dom)
        if not dm or dm.group(1) == "00":
            continue
        base = os.path.join(root, dom, "_agents")
        if not os.path.isdir(base):
            continue
        for name in sorted(os.listdir(base)):
            prompt = os.path.join(base, name, "agents", name + ".md")
            if not os.path.isfile(prompt):
                continue
            meta, body = frontmatter(prompt)
            if meta.get("name") != name:
                raise ValueError("frontmatter name differs from the folder: " + prompt)
            rel = "/".join([dom, "_agents", name])
            kind = "role" if dom.endswith(ROLE_SUFFIX) else "specialist"
            agents.append({
                "name": name,
                "domain": dom,
                "kind": kind,
                "model": model_info(policy, kind, name, meta.get("model", "")),
                "path": rel,
                "prompt": rel + "/agents/" + name + ".md",
                "tools": [t.strip() for t in meta.get("tools", "").split(",") if t.strip()],
                # edits code = has Edit; Write alone (audit roles) only writes artifacts in the authorized directory
                "can_edit": "Edit" in [t.strip() for t in meta.get("tools", "").split(",")],
                "description": meta.get("description", ""),
                "_body": body,
            })
    names = [a["name"] for a in agents]
    for a in agents:
        # Declared boundaries: other agents cited in the canonical prompt.
        a["mentions"] = sorted(n for n in names if n != a["name"] and re.search(
            r"(?<![\w-])" + re.escape(n) + r"(?![\w-])", a["_body"] + a["description"]))
        del a["_body"]
    return agents


def render_md(agents):
    out = ["# Agent catalog of the collection",
           "",
           "Generated by `scripts/build_catalog.py` from the real frontmatter of each agent. "
           "Do not edit by hand: run the script. Paths relative to the `general-agents/` root.",
           "",
           "Total: **%d agents** in **%d domains** (%d specialists with sources; %d role agents, no source, `[practice]` label)." % (
               len(agents), len({a["domain"] for a in agents}),
               sum(a["kind"] == "specialist" for a in agents), sum(a["kind"] == "role" for a in agents)),
           ""]
    dom = None
    for a in agents:
        if a["domain"] != dom:
            dom = a["domain"]
            out += ["", "## " + dom + (" (role agents)" if a["kind"] == "role" else ""), "",
                    "| Agent | Model (Claude / OpenAI) | Edits code | Summary (start of the description) | Cited boundaries |",
                    "|---|---|---|---|---|"]
        first = a["description"]
        if len(first) > 220:
            first = first[:217].rsplit(" ", 1)[0] + "..."
        out.append("| `%s` | %s / %s (%s) | %s | %s | %s |" % (
            a["name"], a["model"]["claude"] or "-", a["model"]["openai"], a["model"]["tier"],
            "yes" if a["can_edit"] else "no", first.replace("|", "/"),
            ", ".join("`%s`" % m for m in a["mentions"]) or "-"))
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description="Generates the agent catalog of the collection.")
    ap.add_argument("--root", default=DEFAULT_ROOT)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    try:
        agents = scan(a.root)
    except (OSError, ValueError, KeyError) as e:
        print("ERROR: %s" % e, file=sys.stderr)
        return 2
    if not agents:
        print("ERROR: no agent found in %s" % a.root, file=sys.stderr)
        return 2
    data = json.dumps({"agents": agents}, ensure_ascii=False, indent=1) + "\n"
    md = render_md(agents)
    if a.check:
        stale = []
        for path, new in ((CATALOG, data), (CATALOG_MD, md)):
            try:
                with open(path, "r", encoding="utf-8") as f:
                    if f.read() != new:
                        stale.append(path)
            except OSError:
                stale.append(path)
        if stale:
            print("STALE: " + ", ".join(os.path.relpath(p, PKG) for p in stale)
                  + "\nRun: python -I scripts/build_catalog.py")
            return 1
        print("OK: catalog up to date (%d agents)." % len(agents))
        return 0
    with open(CATALOG, "w", encoding="utf-8", newline="\n") as f:
        f.write(data)
    with open(CATALOG_MD, "w", encoding="utf-8", newline="\n") as f:
        f.write(md)
    print("Catalog generated: %d agents in %d domains." % (len(agents), len({x["domain"] for x in agents})))
    return 0


if __name__ == "__main__":
    sys.exit(main())
