def _cites(txt):
    """pages cited in a fragment '(SBR p.405-406, 410)': set of ints (ranges expanded)."""
    out = set()
    for a, b in re.findall(r"(\d{1,3})(?:\s*[-–]\s*(\d{1,3}))?", txt):
        a = int(a)
        b = int(b) if b else a
        if a <= b <= a + 40:
            out.update(range(a, b + 1))
    return out


def page_summaries(n, width=520):
    """excerpts of the references/*.md summaries whose citation '(SBR p.X[-Y])' covers page n (package paraphrase, not the book)."""
    root = os.path.dirname(C.HERE)
    found = []
    for path in sorted(glob.glob(os.path.join(root, "references", "*.md"))):
        name = os.path.basename(path)
        with open(path, encoding="utf-8") as fh:
            for ln, line in enumerate(fh, 1):
                last = 0
                for m in re.finditer(r"SBR p\.([0-9][0-9\s,\-–]*)", line):
                    if n in _cites(m.group(1)):
                        seg = line[last:m.end()].strip(" -*).;")
                        seg = re.sub(r"^[-*\s]*(\*\*\[[^\]]*\]\*\*)?\s*", "", seg).lstrip(" ]*")
                        found.append((name, ln, seg if len(seg) <= width else "..." + seg[-width:]))
                    last = m.end()
    return found


def cmd_page(idx, n):
    if n < 1 or n > idx["paginas"]:
        print("page outside 1-%d" % idx["paginas"])
        return 2
    pr = C.printed(n)
    print("PDF page %d%s" % (n, (" = printed %d" % pr) if pr else " (cover/table of contents)"))
    # round 4: the table of contents only records the page where each title STARTS; a page can have several titles (the top one comes
    # from the previous page). That is why we separate "section in progress at the top" from "titles that start on this page".
    before = [e for e in idx["toc"] if e["pdf"] < n]
    starts = [e for e in idx["toc"] if e["pdf"] == n]
    ents = before + starts
    if ents:
        chap = [e for e in ents if e["num"] and re.fullmatch(r"\d+|[A-F]", e["num"])]
        sec = [e for e in ents if e["num"] and re.fullmatch(r"\d+\.\d+|[A-F]\.\d+", e["num"])]
        if chap:
            print("  chapter: %s %s (p.%d)" % (chap[-1]["num"], chap[-1]["title"], chap[-1]["pdf"]))
        if before:
            top = before[-1]
            print("  in progress at the TOP of the page (continuation, title started earlier): %s %s (p.%d)" % (top["num"] or "-", top["title"], top["pdf"]))
        if starts:
            print("  titles that START on this page:")
            for e in starts:
                print("    %s %s" % (e["num"] or "-", e["title"]))
        else:
            print("  no table-of-contents title starts on this page (it continues the top title)")
        if sec:
            print("  most recent section (level x.y) up to the end of the page: %s %s (p.%d)" % (sec[-1]["num"], sec[-1]["title"], sec[-1]["pdf"]))
        ref_src = (starts or before)[-1]
        ref = toc_ref(ref_src["num"] if ref_src["num"] else (sec or chap or [ref_src])[-1]["num"])
        if ref:
            print("  topical reference: references/%s" % ref)
    props = [k for k, v in idx["props"].items() if n in v["apendice_a"] or n in v["corpo"]]
    if props:
        print("  properties on this page (%d): %s%s" % (len(props), ", ".join(props[:15]), " ..." if len(props) > 15 else ""))
    ids = [k for k, pg in idx["ids"].items() if n in pg]
    if ids:
        print("  identifiers on this page (%d): %s%s" % (len(ids), ", ".join(ids[:20]), " ..." if len(ids) > 20 else ""))
    # round 14: package summaries that cite this page (paraphrase; the script does NOT carry the book text)
    sm = page_summaries(n)
    if sm:
        print("  package summaries that cite SBR p.%d (package paraphrase, not the book; %d excerpt(s)):" % (n, len(sm)))
        for name, ln, seg in sm[:8]:
            print("    references/%s:%d: %s" % (name, ln, seg))
        if len(sm) > 8:
            print("    ... (+%d excerpts; open the topical reference)" % (len(sm) - 8))
    else:
        print("  no references/ summary cites SBR p.%d: the package does not carry the content of this page (only the metadata above); say so and do NOT invent." % n)
    return 0


def cmd_chapters(idx):
    for e in idx["toc"]:
        if e["num"] and (re.fullmatch(r"\d+", e["num"]) or re.fullmatch(r"[A-F]", e["num"] or "")) or (e["title"].startswith("Appendix")):
            print("%-3s %-45s PDF p.%-4d (printed %d)" % (e["num"] or "-", e["title"], e["pdf"], e["printed"]))
    return 0


def cmd_toc(idx, num):
    n = 0
    for e in idx["toc"]:
        if e["num"] and (e["num"] == num or e["num"].startswith(num + ".")):
            print("%-8s %s -> p.%d (printed %d)" % (e["num"], e["title"], e["pdf"], e["printed"]))
            n += 1
    if not n:
        print("NOT COVERED: section %s is not in the table of contents" % num)
        return 2
    return 0


