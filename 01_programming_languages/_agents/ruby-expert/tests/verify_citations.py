# -*- coding: utf-8 -*-
"""
verify_citations.py - audits the ruby-expert package citations against the text extracted from the PDFs.

Usage:
  python -I tests/verify_citations.py --src FOLDER_WITH_TXT_FILES [--checks tests/citation-checks.json] [-v]
FOLDER_WITH_TXT_FILES contains Ruby-3.0-Release-Notes.txt ... Ruby-3.4-Release-Notes.txt, generated by tests/extract_pages.py
(markers "=== PAGE N ===", N = PDF page).

Layers:
 1. Curated POSITIVES (citation-checks.json): all 'terms' must appear on at least one of the cited pages.
 2. Curated NEGATIVES: no 'term' may appear on ANY page of the five notes (plausible claims that the
    text does not contain). Prefix 're:' = regular expression.
 3. PAGE RANGE: every citation (R3x p.N[-M]) in agents/, references/, skills/ and README must be within the number of
    pages of the note.
 4. SKILL DATA: each item of ruby_feature_index.json and ruby_version_data.json has 'terms' that must appear on the
    'cite' pages.
No network, read-only. Exit 0 if everything passed.
"""
import argparse
import glob
import json
import os
import re
import sys
import unicodedata

for _s in (sys.stdout, sys.stderr):
    try:
        _s.reconfigure(encoding="utf-8")
    except Exception:
        pass

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REL = {"R30": "Ruby-3.0-Release-Notes", "R31": "Ruby-3.1-Release-Notes", "R32": "Ruby-3.2-Release-Notes",
       "R33": "Ruby-3.3-Release-Notes", "R34": "Ruby-3.4-Release-Notes"}


def clean(s):
    s = unicodedata.normalize("NFKC", s).replace("’", "'").replace("‘", "'")
    s = s.replace("“", '"').replace("”", '"').replace("\xa0", " ")
    return re.sub(r"\s+", " ", s)


def load(src):
    books = {}
    for sig, name in REL.items():
        p = os.path.join(src, name + ".txt")
        raw = open(p, encoding="utf-8").read()
        parts = re.split(r"=== PAGE (\d+) ===", raw)
        books[sig] = {int(parts[i]): clean(parts[i + 1]) for i in range(1, len(parts), 2)}
    return books


def has(text, term):
    term = clean(term)
    if term.startswith("re:"):
        return re.search(term[3:], text, re.IGNORECASE) is not None
    return term.lower() in text.lower()


def blob(books, cite):
    return " ".join(books[r].get(p, "") for r, pages in cite for p in pages)


def expand(spec):
    out = []
    for tok in re.split(r"\s*,\s*", spec.strip()):
        m = re.fullmatch(r"(\d+)(?:\s*-\s*(\d+))?", tok)
        if m:
            out += list(range(int(m.group(1)), int(m.group(2) or m.group(1)) + 1))
    return out


CITE = re.compile(r"\((R3[0-4] p\.[\d,\s\-]+(?:;\s*R3[0-4] p\.[\d,\s\-]+)*)\)")


def check_ranges(books):
    bad, total = [], 0
    files = []
    for pat in ("agents/*.md", "references/*.md", "README.md", "AGENTS.md", ".github/agents/*.md",
                "skills/*/SKILL.md", "skills/*/scripts/*.py", "skills/*/scripts/*.json", "tests/*.md"):
        files += glob.glob(os.path.join(ROOT, pat))
    for f in sorted(files):
        txt = open(f, encoding="utf-8").read()
        for m in re.finditer(r"(R3[0-4]) p\.([\d,\s\-]+)", txt):
            rel, spec = m.group(1), m.group(2)
            for p in expand(spec):
                total += 1
                if p < 1 or p > max(books[rel]):
                    bad.append("%s: %s p.%s out of range (1-%d)" % (os.path.relpath(f, ROOT), rel, p, max(books[rel])))
    return total, bad


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", required=True)
    ap.add_argument("--checks", default=os.path.join(ROOT, "tests", "citation-checks.json"))
    ap.add_argument("-v", "--verbose", action="store_true")
    a = ap.parse_args()
    books = load(a.src)
    for sig, d in books.items():
        print("%s: %d pages" % (sig, len(d))) if a.verbose else None
    checks = json.load(open(a.checks, encoding="utf-8"))
    fails = []

    for c in checks["positive"]:
        b = blob(books, c["cite"])
        miss = [t for t in c["terms"] if not has(b, t)]
        if miss:
            fails.append(c["id"])
            print("FAIL", c["id"], c["cite"], "-", c["claim"], "| missing:", miss)
        elif a.verbose:
            print("OK   ", c["id"], c["claim"])

    allp = " ".join(t for d in books.values() for t in d.values())
    for c in checks["negative"]:
        found = [t for t in c["terms"] if has(allp, t)]
        if found:
            fails.append(c["id"])
            print("FAIL", c["id"], "(negative)", c["claim"], "| found:", found)
        elif a.verbose:
            print("OK   ", c["id"], "(negative)", c["claim"])

    total, bad = check_ranges(books)
    for b in bad:
        fails.append("range")
        print("FAIL range:", b)

    sk = 0
    for jf, key in (("skills/ruby-feature-lookup/scripts/ruby_feature_index.json", "features"),
                    ("skills/ruby-version-lookup/scripts/ruby_version_data.json", "versions")):
        data = json.load(open(os.path.join(ROOT, jf), encoding="utf-8"))[key]
        items = data if key == "features" else [h for v in data for h in v["highlights"]]
        for it in items:
            sk += 1
            b = blob(books, it["cite"])
            miss = [t for t in it["terms"] if not has(b, t)]
            if miss:
                fails.append("skill:" + it.get("id", it["text"][:20]))
                print("FAIL skill", os.path.basename(jf), it.get("id", it.get("text", "")[:40]), it["cite"], "| missing:", miss)

    print("Summary: %d positive, %d negative, %d page citations checked in range, %d skill items, %d failures"
          % (len(checks["positive"]), len(checks["negative"]), total, sk, len(fails)))
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
