# ---------------------------------------------------------------- book index
class Book:
    def __init__(self, idx, synonyms):
        self.ok = idx is not None
        self.terms = idx["terms"] if self.ok else {}
        self.common = idx["common"] if self.ok else {}
        self.meta = idx["_meta"] if self.ok else {}
        self.syn = synonyms or {}

    def _pages_exact(self, t):
        if t in self.terms:
            return set(self.terms[t])
        return None

    def similar(self, unit, n=3):
        """index terms with similar spelling (suggestion only; proves nothing): [(term, pages)]"""
        if not self.ok or len(unit) < 4:
            return []
        import difflib
        cand = [t for t in self.terms if abs(len(t) - len(unit)) <= 2 and t[0] == unit[0]]
        return [(t, self.terms[t]) for t in difflib.get_close_matches(unit, cand, n=n, cutoff=0.8)]

    def pages(self, unit):
        """(pages or None, True if the word is very common). Tries synonyms and parts of hyphenated terms."""
        if not self.ok:
            return None, False
        if unit in self.common:
            return set(), True
        p = self._pages_exact(unit)
        # round 9: the term and its synonyms (e.g. encryption + encrypted) add up their pages; does not stop at the first hit
        acc = set(p) if p else set()
        for alt in self.syn.get(unit, []):
            for v in [alt] + sorted(variants(alt)):
                q = self._pages_exact(v)
                if q:
                    acc |= set(q)
        if acc:
            return acc, False
        for v in sorted(variants(unit)):
            q = self._pages_exact(v)
            if q:
                return q, False
        if unit.endswith("++"):
            q = self._pages_exact(unit.rstrip("+"))
            if q:
                return q, False
        if "-" in unit or "_" in unit:
            parts = [x for x in re.split(r"[-_]", unit) if len(x) >= 2 and x not in STOP_EN]
            ps = [self._pages_exact(x) for x in parts]
            ps = [x for x in ps if x]
            if ps and len(ps) == len(parts):
                inter = set.intersection(*ps)
                return (inter if inter else set.union(*ps)), False
        return None, False


# ---------------------------------------------------------------- summaries index (references/*.md)
def norm_words(text):
    """normalized text as space-separated words (hyphen becomes space), to check a whole phrase"""
    return " ".join(re.findall(r"[a-z0-9+]+", prep(text)))


_SYM = {"→": "->", "≤": "<=", "≥": ">=", "–": "-", "—": "-", "×": "x", "“": '"', "”": '"',
        "‘": "'", "’": "'", "≈": "~", "−": "-", "·": ".", "…": "..."}


def ascii_fold(text):
    """the lookup output is ASCII (like the rest of the package): no accents, common symbols replaced"""
    for k, v in _SYM.items():
        text = text.replace(k, v)
    text = unicodedata.normalize("NFKD", text)
    return "".join(c for c in text if not unicodedata.combining(c)).encode("ascii", "ignore").decode("ascii")


class Refs:
    """Term index of the content of the summaries in references/ (ref_term_index.json). COVERED only comes from here."""

    def __init__(self, idx):
        self.ok = idx is not None
        self.chunks = idx["chunks"] if self.ok else []
        self.terms = idx["terms"] if self.ok else {}
        self.parts = idx["parts"] if self.ok else {}
        self.limit = idx["limit_terms"] if self.ok else {}
        self.meta = idx["_meta"] if self.ok else {}
        ns = self.meta.get("n_summary_chunks", 0)
        self.generic_df = max(30, int(0.05 * ns))  # a term in more chunks than this is generic (does not identify the topic)

    @staticmethod
    def forms(unit, syn):
        out = set()
        for w in [unit] + list((syn or {}).get(unit, [])):
            out |= variants(w)
        return out

    def whole_ids(self, unit, syn):
        ids = set()
        for f in self.forms(unit, syn):
            ids.update(self.terms.get(f, ()))
        return ids

    def part_ids(self, unit, syn, phrase):
        ids = set()
        for f in self.forms(unit, syn):
            ids.update(self.parts.get(f, ()))
        return set(i for i in ids if word_in(phrase, norm_words(self.chunks[i][4])))

    def limit_ids(self, unit, syn):
        ids = set()
        for f in self.forms(unit, syn):
            ids.update(self.limit.get(f, ()))
        return ids

    def analyze(self, qunits, syn, common=()):
        """{treated: {unit: ids}, generic: set, qualifies: bool, passages: [ids], notes: [ids]}. Whole words in the summary body only."""
        res = {"treated": {}, "generic": set(), "qualifies": False, "passages": [], "notes": []}
        if not self.ok:
            return res
        phrase = " ".join(qunits)
        multi = len(qunits) >= 2
        for u in qunits:
            ids = self.whole_ids(u, syn)
            if not ids and multi:
                ids = self.part_ids(u, syn, phrase)  # part of a hyphenated term: only if the whole query phrase appears in the text
            if ids:
                res["treated"][u] = ids
        # generic = very common word in the book (book index) or present in many summaries: does not identify the topic
        res["generic"] = {u for u in qunits if u in common or len(res["treated"].get(u, ())) > self.generic_df}
        informative = [u for u in qunits if u not in res["generic"]]
        tr_inf = [u for u in informative if u in res["treated"]]
        if informative:
            # up to 2 informative terms: all must be in the summary body; with 3 or more, at least 2/3
            need = len(informative) if len(informative) <= 2 else -(-2 * len(informative) // 3)
            res["qualifies"] = len(tr_inf) >= max(1, need)
        else:
            res["qualifies"] = bool(qunits) and all(u in res["treated"] for u in qunits)
        # passages: those covering the most units (whole phrase and frequency break ties)
        cnt = {}
        for u, ids in res["treated"].items():
            for i in ids:
                cnt[i] = cnt.get(i, 0) + 1
        top = sorted(cnt, key=lambda i: (-cnt[i], i))[:80]
        sc = {}
        for i in top:
            nw = norm_words(self.chunks[i][4])
            tf = sum(nw.split().count(f) for u in res["treated"] for f in self.forms(u, syn))
            sc[i] = cnt[i] * 10 + (25 if multi and word_in(phrase, nw) else 0) + min(tf, 5)
        order = sorted(top, key=lambda i: (-sc[i], i))
        keep, seen = [], set()
        for i in order:
            cov = {u for u, ids in res["treated"].items() if i in ids}
            if not keep or (cov - seen) or cnt[i] == cnt[keep[0]]:
                keep.append(i)
                seen |= cov
            if len(keep) >= 5:
                break
        res["passages"] = keep
        lc = {}
        for u in qunits:
            for i in self.limit_ids(u, syn):
                lc[i] = lc.get(i, 0) + 1
        res["notes"] = sorted(lc, key=lambda i: (-lc[i], i))[:3]
        return res

    def show_chunk(self, i, width=900, focus=()):
        f, ln, k, pg, text = self.chunks[i]
        text = ascii_fold(text)
        if len(text) > width:
            # window around the first occurrence (whole word) of a query term
            pos = None
            for w in sorted(focus, key=len, reverse=True):
                m = re.search(r"(?<![a-z0-9])" + re.escape(w) + r"(?![a-z0-9])", text.lower())
                if m and (pos is None or m.start() < pos):
                    pos = m.start()
            a0 = 0 if pos is None else max(0, pos - width // 3)
            seg = text[a0:a0 + width]
            if a0 > 0:
                seg = "..." + seg.split(" ", 1)[-1]
            if a0 + width < len(text):
                seg = seg.rsplit(" ", 1)[0] + " ..."
            text = seg
        pgs = ("pages %s (PDF)" % fmt_pages(pg, 12)) if pg else "no page in the text"
        print("  [%s:%d] %s" % (f, ln, pgs))
        print("    %s" % text)


def ambiguous_hits(qunits, amb):
    """query terms with more than one sense in the book (e.g. flow, shadow, dns): list of {term, senses}"""
    qs = set(qunits)
    return [a for a in (amb or []) if norm(a["term"]) in qs]


def print_ambiguous(hits):
    for a in hits:
        print("\nALERT: '%s' has more than one sense in the book; check which one the question means:" % a["term"])
        for s in a["senses"]:
            print("  - %s" % ascii_fold(s))


def fmt_pages(ps, limit=14):
    ps = sorted(ps)
    if len(ps) > limit:
        return ", ".join(str(x) for x in ps[:limit]) + " ... (%d pages)" % len(ps)
    return ", ".join(str(x) for x in ps)


# ---------------------------------------------------------------- curated list and topics
# words that, before a number, indicate a locator/measure (not a product name): "capitulo 17" (chapter 17), "figura 3" (figure 3), "sev 1"
_LOCATORS = set("""cap capitulo capitulos chapter chapters pagina paginas page pages pag fig figura figure tabela table nota note
secao section parte part passo step fase phase nivel level tier sev severidade severity release versao version rfc fn p pp
top ano anos year years dia dias day days hora horas hour hours min minuto minutos mes meses month months semana semanas week
weeks vez vezes nines noves replica replicas node nodes cluster clusters datacenter datacenters task tasks job jobs""".split())
_PRODUCT_NUM = re.compile(r"(?<![a-z0-9])([a-z][a-z-]{2,})\s+(\d{1,4})(?![a-z0-9]|[.,]\d|\s*%)")


def product_names(query, refs, syn, common):
    """Product/service name (cloud etc.) with a number, e.g. 'Route 53'. Round 14: the bare word ('route') exists in the book
    in another sense and made the product become POINTER ONLY. Rule: word + number (1-4 digits) where the word is NOT treated
    in any summary, is not common in the book and is not a locator ('capitulo 17' (chapter 17), 'figura 3' (figure 3)) => product name,
    which does not match by the bare word.
    Returns [(word, number)]."""
    out = []
    if not refs.ok:
        return out
    for m in _PRODUCT_NUM.finditer(norm(query)):
        w, n = m.group(1), m.group(2)
        if w in _LOCATORS or w in STOP_Q or w in STOP_EN or w in common:
            continue
        ids = refs.whole_ids(w, syn)
        if ids:
            # the bare word is treated in the summaries. In English summaries ordinary words ('route') are treated too, so a word that is
            # rare in the summaries and never appears next to this number (no 'route 53' in any summary) is still a product name.
            pair = re.compile(r"(?<![a-z0-9])%s\s+%s(?![a-z0-9])" % (re.escape(w), n))
            if len(ids) >= 10 or any(pair.search(norm(refs.chunks[i][4])) for i in ids):
                continue
        out.append((w, n))
    return out


def out_of_book_hits(query, oob):
    """Terms that are NOT in the book and that appear in the query (checked BEFORE the topics)."""
    qn = norm(query)
    return [o for o in oob if re.search(o["re"], qn)]


def show(key, t):
    print("TOPIC: %s [%s]" % (t["name"], key))
    print("CITATION: [from source] (%s)" % t["citation"])
    print("\nSUMMARY: %s" % t["summary"])
    print("\nRULES FROM THE BOOK (with page):")
    for r in t["rules"]:
        print("  * [from source] %s" % r)
    if t.get("not_in_book"):
        print("\nNOT IN THE SOURCE (label [extrapolation] or refuse the attribution):")
        for n in t["not_in_book"]:
            print("  - %s" % n)


def expand_parts(tokens):
    """as in the indexer: parts of hyphen/underscore tokens and base of tokens ending in ++"""
    out = set(tokens)
    for x in tokens:
        if "-" in x or "_" in x:
            for q in re.split(r"[-_]", x):
                if len(q) >= 2 and q not in STOP_EN:
                    out.add(q)
        if x.endswith("++"):
            out.add(x.rstrip("+"))
    return out


def topic_tokens(t, key):
    names = [key, t["name"]] + t.get("keywords", []) + t.get("aliases", [])
    kw = set()
    for n in names:
        kw |= set(simple_tokens(n))
    blob = expand_parts(simple_tokens(t["name"] + " " + t["summary"] + " " + " ".join(t["rules"])))
    return names, kw, blob


def treats(unit, blob, syn):
    """the topic summary/rules (blob) treat the query unit (the word itself or a pt/en synonym)"""
    forms = {unit, unit + "s", unit + "es"}
    if unit.endswith("s"):
        forms.add(unit[:-1])
    if unit.endswith("es"):
        forms.add(unit[:-2])
    if forms & blob:
        return True
    for a in (syn or {}).get(unit, []):
        if a in blob or a + "s" in blob or (a.endswith("s") and a[:-1] in blob):
            return True
    return False


def score_topic(qn, qunits, key, t, syn=None):
    """(score, qualifies, covered_tokens). Matching by whole phrase or by word coverage (no loose substrings).
    Round 4: the topic only qualifies (COVERED) if the SUMMARY/RULES treat at least one query term; matching only by
    keyword or name is not enough (avoids the misleading COVERED for 'root cause' and 'push')."""
    names, kw, blob = topic_tokens(t, key)
    best = 0
    for n in names:
        nn = norm(n)
        if not nn:
            continue
        if qn == nn:
            best = max(best, 1000)
        elif word_in(nn, qn):
            best = max(best, 500 + len(nn))
        elif word_in(qn, nn):
            best = max(best, 300 + len(qn))
    cov_kw = [u for u in qunits if u in kw]
    cov_blob = [u for u in qunits if treats(u, blob, syn) and u not in kw]
    treated = [u for u in qunits if treats(u, blob, syn)]
    score = best + 40 * len(cov_kw) + 10 * len(cov_blob)
    phrase_blob = len(qn) >= 4 and len(qn.split()) >= 2 and word_in(qn, norm(t["summary"] + " " + " ".join(t["rules"])))
    if phrase_blob:
        score += 30
    covered = set(treated)
    full = bool(qunits) and len(covered) == len(qunits) and len(cov_kw) >= 1
    half = len(cov_kw) >= 2 and len(cov_kw) * 2 >= len(qunits)
    qualifies = (best > 0 or full or half or phrase_blob) and len(treated) > 0
    return score, qualifies, covered

def rank_topics(query, topics, qunits, syn=None):
    qn = norm(query).strip()
    ranked = []
    for k, t in topics.items():
        s, ok, cov = score_topic(qn, qunits, k, t, syn)
        if ok and s > 0:
            ranked.append((s, k, cov))
    ranked.sort(key=lambda x: (-x[0], x[1]))
    return ranked


def score(q, key, t):
    """compatibility: simple score of a topic for a query"""
    return score_topic(norm(q).strip(), units_of(q), key, t)[0]


def keyword_issues(topics, syn):
    """[(topic, [keywords whose term appears neither in the summary/rules nor in a synonym])]: guarantees that COVERED only occurs
    when the topic summary treats the term."""
    out = []
    for k, t in topics.items():
        blob = expand_parts(simple_tokens(t["summary"] + " " + " ".join(t["rules"]) + " " + t["name"]))
        ws = []
        for kwd in t.get("keywords", []):
            toks = simple_tokens(kwd)
            if toks and not all(treats(x, blob, syn) for x in toks):
                ws.append(kwd)
        if ws:
            out.append((k, ws))
    return out


# ---------------------------------------------------------------- main
def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("query", nargs="*", help="term(s); several words are joined")
    ap.add_argument("--list", action="store_true")
    ap.add_argument("--topic")
    ap.add_argument("--pages", help="show the book pages (PDF) where the term occurs, according to the book index")
    ap.add_argument("--max", type=int, default=3)
    ap.add_argument("--ref-index", help=argparse.SUPPRESS)  # for tests only: another ref_term_index.json
    ap.add_argument("--check", action="store_true",
                    help="consistency: every keyword of each topic must appear in the summary/rules (or in a synonym); rc 1 on failure")
    a = ap.parse_args(argv)
    data = load_all()
    topics = data["topics"]
    oob = data.get("out_of_book", [])
    book = Book(load_book_index(), data.get("synonyms", {}))
    refs = Refs(load_ref_index(a.ref_index))
    if a.check:
        bad = keyword_issues(topics, data.get("synonyms", {}))
        for k, ws in bad:
            print("topic %s: keyword not treated in the summary/rules: %s" % (k, ", ".join(ws)))
        print("consistency: %d topics, %d with untreated keyword" % (len(topics), len(bad)))
        return 1 if bad else 0
    if a.list:
        for k, t in topics.items():
            print("%-28s %s (%s)" % (k, t["name"], t["citation"]))
        return 0
    if a.topic:
        if a.topic not in topics:
            print("Unknown topic: %s. Use --list." % a.topic)
            return 2
        show(a.topic, topics[a.topic])
        return 0
    if a.pages:
        if not book.ok:
            print("Book index missing (book_term_index.json): cannot assert presence or absence.")
            return 2
        us = units_of(a.pages)
        if not us:
            print("Provide a term.")
            return 2
        rc = 1
        for u in us:
            ps, common = book.pages(u)
            if common:
                print("%s: term very common in the book (%d pages); search for a more specific term." % (u, book.common.get(u, 0)))
                rc = 0
            elif ps:
                print("%s: pages %s (PDF; printed = N-12)" % (u, fmt_pages(ps, 40)))
                rc = 0
            else:
                print("%s: not found in the book's term index (whole word + simple inflections + synonyms). "
                      "This does NOT prove the book does not address the topic: try plural/inflection/another spelling/English and read the page." % u)
                for t, ps in book.similar(u):
                    print("   similar spelling in the index: '%s' pages %s" % (t, fmt_pages(ps, 10)))
        return rc
    query = " ".join(a.query).strip()
    if not query:
        ap.print_help()
        return 2
    qunits = units_of(query)
    if not qunits:
        print("Query without a meaningful term. Use words from the topic (e.g. 'error budget', 'Knight Capital').")
        return 2

    # (0) product/service name with a number ('Route 53'): does not match by the bare word
    prods = product_names(query, refs, book.syn, book.common)
    if prods:
        names = ", ".join("'%s %s'" % p for p in prods)
        print("NOT COVERED in the collection for the product/service name %s (name with a number; does not match by the bare word)." % names)
        for w, _n in prods:
            ps, _c = book.pages(w)
            if ps:
                print("  The bare word '%s' occurs in the book (pages %s, PDF) in another sense; this is NOT coverage of the product."
                      % (w, fmt_pages(ps, 8)))
        print("Label [extrapolation] or route to another agent; say 'I did not find it in the extracted text', not 'the book does not say'.")
        drop = set(x for p in prods for x in p)
        qunits = [u for u in qunits if u not in drop]
        if not qunits:
            return 1
        print("")
        query = " ".join(qunits)

    # (1) curated list of things OUTSIDE the book, checked before the topics
    oob_hits = out_of_book_hits(query, oob)
    if oob_hits:
        for o in oob_hits:
            print("NOT COVERED in the collection for the term '%s': NOT IN THE SOURCE (SRE 2016)." % o["term"])
            print("  %s" % o["note"])
        print("Any answer about this must be labeled [extrapolation] or routed; do not attribute it to the book.")
        rel = rank_topics(query, topics, qunits, book.syn)[:2]
        if rel:
            print("")
            print("Nearby topics, for context only (they do NOT treat the term above): " + ", ".join(k for _, k, _ in rel)
                  + "  (use --topic <key>)")
        return 1

    # (2) COVERED: ONLY if the term (whole word) is in the body of a references summary (ref_term_index.json)
    res = refs.analyze(qunits, book.syn, book.common)
    treated = set(res["treated"])
    leftover = [u for u in qunits if u not in treated]
    if not refs.ok:
        print("WARNING: ref_term_index.json missing (run build_ref_index.py); without it COVERED is not asserted.", file=sys.stderr)

    def leftover_report():
        """terms without a summary: pointer (exists in the book) or absent (no occurrence)"""
        pointers, absent = [], []
        for u in leftover:
            ps, common = book.pages(u)
            if common:
                continue
            if ps:
                pointers.append((u, ps))
            else:
                absent.append(u)
        return pointers, absent

    def print_notes():
        if res["notes"]:
            print("\nLIMIT NOTES from the package (what the book does NOT cover or only names; informational, not a summary):")
            for i in res["notes"]:
                refs.show_chunk(i, 500, focus=set().union(*[refs.forms(u, book.syn) for u in qunits]))

    if res["qualifies"]:
        ranked = rank_topics(query, topics, qunits, book.syn)
        if ranked:
            keep, seen = [], set()
            for s_, k, cov in ranked:
                if not keep or s_ * 5 >= keep[0][0] * 2 or (cov - seen):
                    keep.append((s_, k, cov))
                    seen |= cov
            ranked = keep[: a.max]
        print("LEVEL: COVERED (the term is in the body of package summaries, with page; read the passages below)")
        print("")
        print("SUMMARIES IN THE REFERENCES (file:line; PDF pages):")
        focus = set()
        for u in res["treated"]:
            focus |= refs.forms(u, book.syn)
        for i in res["passages"]:
            refs.show_chunk(i, focus=focus)
        for s_, k, _ in ranked:
            print("\n" + "-" * 60 + "\n")
            show(k, topics[k])
        print_ambiguous(ambiguous_hits(qunits, data.get("ambiguous_terms")))
        print_notes()
        pointers, absent = leftover_report()
        if pointers or absent:
            print("\n" + "-" * 60)
            print("Query terms WITHOUT a summary in the package:")
            for u, ps in pointers:
                print("  - '%s': POINTER ONLY, the book has the term on pages %s (PDF); the package does not summarize it." % (u, fmt_pages(ps)))
            for u in absent:
                if book.ok:
                    print("  - '%s': not found in the book's term index (does not prove absence; try plural/inflection/English)." % u)
                else:
                    print("  - '%s': book index missing; do not claim the book does not cover it." % u)
        return 0

    if treated:
        print("Note: %s appear(s) in summaries, but the query as a whole was not covered (not COVERED)." %
              ", ".join("'%s'" % u for u in sorted(treated)))

    # (3) no topic: pointer or true absence
    if not book.ok:
        print("NOT COVERED in the collection for: %s" % query)
        print("(book index missing: book_term_index.json; do NOT claim the book does not cover the topic; say the package does not summarize it)")
        return 1
    pointers, absent = leftover_report()
    commons = [u for u in qunits if book.pages(u)[1]]
    if pointers and not absent:
        print("LEVEL: POINTER ONLY (the book has the term; the package does not summarize it)")
        for u, ps in pointers:
            print("  - '%s': pages %s (PDF; printed = N-12)" % (u, fmt_pages(ps)))
        if len(pointers) > 1:
            inter = set.intersection(*[ps for _, ps in pointers])
            if inter:
                print("  pages with ALL the terms: %s" % fmt_pages(inter))
        print("What to do: say the book covers or mentions the topic on those pages and that the package has no summary; "
              "do not invent content; the exact context is only confirmed by reading the page.")
        print_notes()
        return 3
    if pointers and absent:
        print("NOT COVERED for: %s (not found in the book's term index; this does not prove the book does not address the topic)." %
              ", ".join("'%s'" % u for u in absent))
        print("Partial POINTER (the book has these terms, the package does not summarize them):")
        for u, ps in pointers:
            print("  - '%s': pages %s (PDF; printed = N-12)" % (u, fmt_pages(ps)))
        print("Label the uncovered part [extrapolation]; do not attribute it to the book.")
        print_notes()
        return 1
    if commons and not absent:
        print("LEVEL: POINTER ONLY (terms very common in the book: %s); refine the query with a specific term." % ", ".join(commons))
        print_notes()
        return 3
    print("NOT COVERED in the collection for: %s" % query)
    print("Not found: %s in the book's term index (extracted text, %d pages; whole-word search with simple inflections "
          "and pt/en synonyms). This does NOT prove the book does not address the topic: the index does not see figures or "
          "other spellings. Before claiming 'the book does not cover this', retry in English/singular/another inflection, use --pages and, if "
          "possible, read the page. With no occurrence, the answer must be labeled [extrapolation] or routed to another agent "
          "(observability, DORA, security, containers); say 'I did not find it in the extracted text', not 'the book does not say'." %
          (", ".join("'%s'" % u for u in absent), book.meta.get("pages", 0)))
    for u in absent:
        for t, ps in book.similar(u):
            print("  similar spelling in the book index: '%s' pages %s (PDF); check whether it is the same term." % (t, fmt_pages(ps, 10)))
    print_notes()
    return 1


