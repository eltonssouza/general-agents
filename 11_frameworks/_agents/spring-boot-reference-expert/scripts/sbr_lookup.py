_TOKEN = re.compile(r"[a-z0-9]+(?:[._\-][a-z0-9]+)*")


def _norm_text(s):
    s = s.lower()
    for a in ("‘", "’", "�", "“", "”"):
        s = s.replace(a, "'")
    for a in ("‐", "‑", "–", "—", "−"):
        s = s.replace(a, "-")
    return s


def load_json(path):
    try:
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError):
        return None


def query_parts(terms):
    """query words (without @), as in the index generator."""
    out = []
    for t in _TOKEN.findall(_norm_text(" ".join(terms))):
        out.append(t)
    return out


def variants(w):
    v = {w}
    if w.endswith("ies") and len(w) > 4:
        v.add(w[:-3] + "y")
    if w.endswith("y") and len(w) > 3:
        v.add(w[:-1] + "ies")
    if w.endswith("es") and len(w) > 4:
        v.add(w[:-2])
    if w.endswith("s") and len(w) > 3:
        v.add(w[:-1])
    v.add(w + "s")
    v.add(w + "es")
    if w.endswith("ing") and len(w) > 5:
        v.add(w[:-3])
    return v


def unpack(spec):
    pgs = set()
    for tk in spec.split(","):
        if "-" in tk:
            a, b = tk.split("-")
            pgs.update(range(int(a), int(b) + 1))
        elif tk:
            pgs.add(int(tk))
    return pgs


def text_pages(terms, T):
    """Reference pages where the term/phrase occurs (term index); empty set if it does not occur."""
    if not T:
        return set()
    uni, bi = T["unigramas"], T["bigramas"]
    toks = query_parts(terms)
    if not toks:
        return set()
    # whole token (e.g. spring.rabbitmq.listener.type, datajpatest)
    if len(toks) == 1:
        pg = set()
        for v in variants(toks[0]):
            if v in uni:
                pg |= unpack(uni[v])
        if pg:
            return pg
        # stem (D6, round 4): 'autoscal' finds autoscaling/autoscaler; only a simple word of 5+ letters, at the START of the word
        w = toks[0]
        if len(w) >= 5 and re.fullmatch(r"[a-z0-9]+", w):
            for k, v in uni.items():
                if k.startswith(w):
                    pg |= unpack(v)
            return pg
    parts = []
    for t in toks:
        parts.extend(p for p in re.split(r"[._\-]", t) if p)
    if len(parts) == 1:
        pg = set()
        for v in variants(parts[0]):
            if v in uni:
                pg |= unpack(uni[v])
        return pg
    res = None
    for x, y in zip(parts, parts[1:]):
        pg = set()
        for vx in variants(x):
            for vy in variants(y):
                k = vx + " " + vy
                if k in bi:
                    pg |= unpack(bi[k])
        res = pg if res is None else (res & pg)
        if not res:
            return set()
    return res


def fmt_set(pgs, limit=14):
    ps = sorted(pgs)
    return ",".join(str(p) for p in ps[:limit]) + ("..." if len(ps) > limit else "")


def _has_sub(seq, sub):
    """True if the word list 'sub' appears contiguously in 'seq' (whole-WORD matching, never part of a word)."""
    n = len(sub)
    return n > 0 and any(seq[i:i + n] == sub for i in range(len(seq) - n + 1))


def curated_match(terms, curated, kind):
    """matches the query against the curated list by whole TOKENS (token = word, or word with . - _ ; e.g. 'git.commit.time'
    is one token and does NOT match the term '@commit'; 'native image' matches when both words appear contiguously)."""
    qw = query_parts(terms)
    qn = re.sub(r"[^a-z0-9]+", "", "".join(qw))
    for e in (curated or {}).get(kind, []):
        for t in e["termos"]:
            tw = _TOKEN.findall(_norm_text(t))
            tn = re.sub(r"[^a-z0-9]+", "", "".join(tw))
            if not tn:
                continue
            if qn == tn or (len(tn) >= 6 and _has_sub(qw, tw)) or (len(qn) >= 6 and _has_sub(tw, qw)):
                return e
    return None


_COVER = None


def load_cover():
    global _COVER
    if _COVER is None:
        data = load_json(COVER_PATH) or {"linhas": [], "sha": None}
        try:
            if data.get("sha") != B.refs_sha():
                sys.stderr.write("WARNING: scripts/sbr_cover.json is out of date relative to references/: run python -I scripts/build_cover_index.py" + chr(10))
        except OSError:
            pass
        _COVER = [(i, p, t.split(), d.split()) for i, p, t, d in data["linhas"]]
    return _COVER


def is_strong(raw):
    """identifier (@Annot, dotted.key, kebab, digit, camelCase) covers anywhere in the summary; a plain common word only when delimited."""
    return bool(re.search(r"[@#._\-=:/\d]", raw) or re.search(r"[a-z][A-Z]", raw))


def _has_phrase(seq, vs):
    n = len(vs)
    if not n:
        return False
    for i in range(len(seq) - n + 1):
        if all(seq[i + j] in vs[j] for j in range(n)):
            return True
    return False


def cover_hits(terms):
    """(hits, loose): hits = (file, line, pages) of references/ summaries that treat the term (WHOLE TERM/CONTIGUOUS PHRASE
    against the body of the summaries); loose = lines where the common word only appears loosely in prose (does not cover)."""
    raw = " ".join(terms)
    q = B.tokenize(raw)
    if not q:
        return [], []
    strong = len(q) > 1 or is_strong(raw)
    # compound identifier (git-commit-id, spring.config.import): the WHOLE PARTS of the query must appear contiguously among
    # the parts of the summary tokens (git-commit-id finds git-commit-id-plugin); never part of a word, and a one-word
    # query (record) compares the whole token (does not find max-poll-records).
    qp = [p for w in q for p in re.split(r"[._\-]", w) if p]
    compound = len(q) == 1 and len(qp) > 1
    vs = [variants(w) for w in (qp if compound else q)]
    hits, soltas = [], []
    for i, p, t, d in load_cover():
        name, _, ln = i.rpartition(":")
        if compound:
            seq = [x for w in t for x in re.split(r"[._\-]", w) if x]
            ok = _has_phrase(seq, vs)
        else:
            ok = _has_phrase(t if strong else d, vs)
        if ok:
            hits.append((name, int(ln), p))
        elif not strong and _has_phrase(t, vs):
            soltas.append((name, int(ln), p))
    return hits, soltas


def classify(res, terms):
    """returns (level, justification, text_pages, refs, curated_note, redirect, loose)"""
    T = load_json(TERMS_PATH)
    curated = load_json(CURATED_PATH)
    pages = text_pages(terms, T)
    refs, soltas = cover_hits(terms)
    cp = curated_match(terms, curated, "so_ponteiro")
    cf = curated_match(terms, curated, "fora")
    structured = bool(res["toc"] or res["props"] or res["deps"] or res["ids"])
    if cp:
        pg = pages | (unpack(cp["paginas"]) if cp.get("paginas") else set())
        return ("POINTER ONLY", "curated list of subjects that are only mentioned", pg, refs, cp["nota"], None, soltas)
    if cf:
        if pages or structured:
            return ("POINTER ONLY", "subject of the curated out-of-scope list, but with an occurrence in the text", pages, refs, cf["nota"], cf.get("encaminhar"), soltas)
        return ("NOT COVERED", "curated out-of-scope list and 0 occurrences in the term index", set(), [], cf["nota"], cf.get("encaminhar"), [])
    if not (pages or structured):
        # no occurrence in the Reference text: no package summary can "cover" the term (e.g. notes saying it does not exist)
        return ("NOT COVERED", "0 occurrences in the Reference term index (882 pages)", set(), [], None, None, [])
    if refs:
        return ("COVERED", "a summary with a page in references/ treats the term (whole term/phrase)", pages, refs, None, None, [])
    return ("POINTER ONLY", "the term occurs in the Reference, but no references/ summary treats it", pages | {p for _, pgs in res["ids"] for p in pgs}, refs, None, None, soltas)


def tok(s):
    return re.sub(r"[^a-z0-9]+", "", s.lower())


def toc_ref(num):
    if not num:
        return None
    best = None
    for pre, ref in REF_BY_CHAPTER:
        if num == pre or num.startswith(pre + ".") or (len(pre) == 1 and pre.isalpha() and num.startswith(pre)):
            if best is None or len(pre) > len(best[0]):
                best = (pre, ref)
    return best[1] if best else None


def _parts(s):
    return [p for p in re.split(r"[^a-z0-9]+", _norm_text(s)) if p]


def _contains(entry, qvs):
    """True if the query words appear CONTIGUOUS and WHOLE among the entry words (never part of a word)."""
    return _has_phrase(entry, qvs)


def search(idx, terms, limit):
    qparts = _parts(" ".join(terms))
    qvs = [variants(w) for w in qparts]
    res = {"toc": [], "props": [], "ids": [], "deps": []}
    if not qparts:
        return res
    for e in idx["toc"]:
        if _contains(_parts(e["title"]), qvs):
            res["toc"].append(e)
    qj = "".join(qparts)
    qn = C.norm_key(".".join(qparts)) if len(qparts) == 1 else None
    for k, v in idx["props"].items():
        if _contains(_parts(k), qvs):
            res["props"].append((k, v))
    res["props"].sort(key=lambda kv: (0 if C.norm_key(kv[0]) == qn else 1, 0 if kv[1]["apendice_a"] else 1, kv[0]))
    for k, pgs in idx["ids"].items():
        if _contains(_parts(k), qvs):
            res["ids"].append((k, pgs))
    res["ids"].sort(key=lambda kv: (0 if kv[0].lower().lstrip("@") == qj else 1, len(kv[0])))
    for d in idx["deps"]:
        if _contains(_parts(d["group"] + ":" + d["artifact"]), qvs):
            res["deps"].append(d)
    return res


