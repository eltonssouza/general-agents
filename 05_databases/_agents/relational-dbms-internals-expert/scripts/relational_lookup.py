PT_STOP_DEFAULT = {"em", "de", "do", "da", "dos", "das", "no", "na", "nos", "nas", "um", "uma", "o", "a", "os", "as", "e", "ou", "ao", "aos",
                   "pelo", "pela", "para", "por", "com", "sem", "se", "que", "como", "qual", "quais", "quando", "ha", "eh"}

LEVEL_COBERTO, LEVEL_PONTEIRO, LEVEL_SEM = "COVERED", "POINTER ONLY", "NOT COVERED"
EXIT = {LEVEL_COBERTO: 0, LEVEL_PONTEIRO: 3, LEVEL_SEM: 1}
MAX_TOPICS, MAX_SNIPPETS = 6, 4


def load_json(path):
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def norm(s):
    return norm_match(s)


def has_phrase(haystack, phrase):
    """phrase appears in haystack (both already normalized) as a sequence of whole words."""
    if not phrase:
        return False
    return (" " + phrase + " ") in (" " + haystack + " ")


def variants(q):
    """normalized query + simple plural variations of the last word (trigger/triggers, index/indexes)."""
    out = [q]
    if " " in q:
        out.append(q.replace(" ", "_"))            # "pages per range" also finds the identifier pages_per_range
    head, _, last = q.rpartition(" ")
    pre = head + " " if head else ""
    if len(last) >= 4 and last.endswith("s") and not last.endswith("ss"):
        out.append(pre + last[:-1])
    if len(last) >= 3 and not last.endswith("s"):
        out.append(pre + last + "s")
        out.append(pre + last + "es")
    return out


def phrase_match(text, q):
    return any(has_phrase(text, v) for v in variants(q))


def parse_pages(spec):
    """'p.4-7, p.100-110' -> lista de (a, b)."""
    out = []
    for m in re.finditer(r"p\.(\d+)(?:\s*-\s*(\d+))?", spec):
        a = int(m.group(1))
        b = int(m.group(2) or a)
        out.append((a, b))
    return out


def fmt_pages(pages):
    return "; ".join("%s %s" % (k, v) for k, v in pages.items())


def overlap(pg_a, pg_b):
    """pg_*: {sigla: 'p.1-2, p.9'}; is there any page in common?"""
    for sig, spec in pg_a.items():
        if sig not in pg_b:
            continue
        ra, rb = parse_pages(spec), parse_pages(pg_b[sig])
        if any(a1 <= b2 and a2 <= b1 for a1, b1 in ra for a2, b2 in rb):
            return True
    return False


LITERAL_RE = re.compile(r"\(\s*\*\s*\)")


def squash_lit(s):
    return re.sub(r"\s+", "", s.lower())


def literal_ok(c, raw):
    """query with the (*) symbol, such as count(*): the excerpt must carry the literal call ('lit' field generated by build_ref_index.py,
    since the normalized text loses the symbol and 'count' of 'pin count' would match). Without (*) in the query, always true."""
    if not raw or not LITERAL_RE.search(raw):
        return True
    return squash_lit(raw) in c.get("lit", [])


def alias_groups(q, data):
    """PT/EN equivalence groups whose term EQUALS the query (simple plural tolerated). Returns [(group, [other normalized terms])]."""
    out = []
    for g in data.get("aliases", []):
        terms = [norm(t) for t in g["terms"]]
        if any(q == t or q in variants(t) for t in terms):
            out.append((g, [t for t in terms if t != q and t not in variants(q)]))
    return out


# ---------------------------------------------------------------- summaries (body x pointer)
def load_refs():
    """ref_terms.json, or None if absent. Warns (stderr) if any reference file changed after generation."""
    if not os.path.exists(REFS_PATH):
        return None
    refs = load_json(REFS_PATH)
    stale = []
    for fn, fp in refs["_meta"]["fingerprint"].items():
        try:
            with open(os.path.join(REF_DIR, fn), "rb") as f:
                if hashlib.sha1(f.read()).hexdigest()[:12] != fp:
                    stale.append(fn)
        except OSError:
            pass
    if stale:
        print("WARNING: ref_terms.json is out of date with respect to references/ (%s); run: python -I scripts/build_ref_index.py"
              % ", ".join(stale[:3]), file=sys.stderr)
    return refs


def search_refs(q, refs, raw=None):
    """(body, pointer): lists of (file, excerpt) whose text contains the term q (whole phrase). raw = original query (literal symbols)."""
    body, ptr = [], []
    if refs is None or not q:
        return body, ptr
    for fn, chunks in refs["files"].items():
        for c in chunks:
            if (phrase_match(c["t"], q) or phrase_match(c.get("hn", ""), q)) and literal_ok(c, raw):
                (body if c["k"] == "b" else ptr).append((fn, c))
    return body, ptr


def is_subject(c, q):
    """the term is the SUBJECT of the excerpt: it appears in the section title or at the start (subject) of the excerpt; a passing mention in the middle of a sentence does not count."""
    return phrase_match(c.get("l", ""), q) or phrase_match(c.get("hn", ""), q)


def starts_with_term(c, q):
    """the excerpt STARTS with the term (exact subject) or the section title is the term."""
    return bool(q) and (any(c.get("l", "").startswith(v) for v in variants(q)) or c.get("hn", "") in variants(q))


def rank_topics(body_hits, data, q=None):
    """curated topics (COVERED) whose page map matches the pages cited in the body excerpts that matched (double weight if
    the excerpt is in the topic's reference); more excerpts = better."""
    score = {}
    for fn, c in body_hits:
        bonus = 3 if starts_with_term(c, q) else 1          # round 11: the excerpt whose subject is exactly the term weighs more ("HOT" x "hot standby")
        for t in data["topics"]:
            if t.get("level", "coberto") != "coberto":
                continue
            if c["pg"] and overlap(c["pg"], t["pages"]):
                score[t["id"]] = score.get(t["id"], 0) + (2 if t.get("ref") == fn else 1) * bonus
    by_id = {t["id"]: t for t in data["topics"]}
    ranked = sorted(score, key=lambda i: (-score[i], i))
    return [by_id[i] for i in ranked[:MAX_TOPICS]], score


def pointer_topics_for(q, data):
    """curated topics of level 'ponteiro' whose keywords contain the term as a whole phrase (pointer registry, not a summary)."""
    hits = []
    for t in data["topics"]:
        if t.get("level") != "ponteiro":
            continue
        for kw in t.get("keywords", []):
            k = norm(kw)
            if k and (phrase_match(q, k) or (len(q) >= 4 and phrase_match(k, q))):
                hits.append(t)
                break
    return hits


def search_curated_outside(q, data):
    """entries of the curated list of subjects outside the sources that the query mentions (whole phrase). An entry may carry 'except_when'
    (round 11): phrases in which the same term has another meaning INSIDE the sources (e.g., 'snowflake schema' = snowflake schema, which exists);
    in that case the entry does not apply to the query."""
    out = []
    for n in data.get("not_in_book", []):
        t = norm(n["term"])
        if not (q == t or has_phrase(q, t)):
            continue
        if q != t and any(has_phrase(q, norm(e)) for e in n.get("except_when", [])):
            continue
        out.append(n)
    return out


# ---------------------------------------------------------------- source term index
def expand(spec):
    pages = set()
    for part in spec.split(","):
        if "-" in part:
            a, b = part.split("-")
            pages.update(range(int(a), int(b) + 1))
        else:
            pages.add(int(part))
    return pages


def compress(pages):
    pages = sorted(pages)
    out, start, prev = [], None, None
    for p in pages:
        if start is None:
            start = prev = p
        elif p == prev + 1:
            prev = p
        else:
            out.append((start, prev))
            start = prev = p
    if start is not None:
        out.append((start, prev))
    return ", ".join("p.%d" % a if a == b else "p.%d-%d" % (a, b) for a, b in out)


def term_index_search(query, terms):
    """For each source: pages where ALL (non-common) tokens of the query co-occur. Returns (tokens, {sigla: info})."""
    toks = []
    for t in tokens_of(query):
        if t not in STOP and t not in toks:
            toks.append(t)
    result = {}
    for sig, src in terms["sources"].items():
        sets, generic, ok = [], 0, True
        for t in toks:
            if t in src["terms"]:
                sets.append(expand(src["terms"][t]))
            elif t in src["common"]:
                generic += 1
            else:
                ok = False
                break
        if not ok or not toks:
            continue
        if sets:
            inter = set.intersection(*sets)
            if inter:
                result[sig] = {"pages": sorted(inter), "generic_only": False}
        elif generic == len(toks):
            result[sig] = {"pages": [], "generic_only": True}
    return toks, result


# ---------------------------------------------------------------- Portuguese queries (round 9)
# The sources are in English and the summaries in Portuguese; a question such as "COMMIT em procedimento PL/pgSQL" is not a phrase that appears anywhere.
# Here: (1) discard Portuguese function words; (2) translate PT<->EN tokens ("lookup_lang.pt_en" field of relational_index.json);
# (3) look for the tokens TOGETHER in the same summary excerpt (co-occurrence); (4) if there is none, accept the excerpts that match most of the tokens
# (OR fallback); (5) in the source term index, use the translated version and also the OR fallback (pages with the largest number of terms).
PT_DISTINCT = {"em", "de", "dos", "das", "nos", "nas", "um", "uma", "uns", "umas", "ou", "ao", "aos", "pelo", "pela", "para", "por", "com", "sem",
               "que", "como", "qual", "quais", "quando"}


def lang_cfg(data):
    cfg = data.get("lookup_lang", {})
    stop = set(PT_STOP_DEFAULT) | set(norm(w) for w in cfg.get("stopwords_pt", []))
    pt_en = {norm(k): [norm(x) for x in v] for k, v in cfg.get("pt_en", {}).items()}
    en_pt = {}
    for k, vs in pt_en.items():
        for v in vs:
            en_pt.setdefault(v, []).append(k)
    return stop, pt_en, en_pt


def sing(w):
    return w[:-1] if len(w) > 4 and w.endswith("s") and not w.endswith("ss") else w


def word_forms(w, pt_en, en_pt):
    """accepted forms for a token: itself, simple plural and the PT<->EN translations (also with simple plural)."""
    out = {w, sing(w), w + "s", w + "es"}
    for b in list(out):
        for a in pt_en.get(b, []) + en_pt.get(b, []):
            out.update({a, sing(a), a + "s", a + "es"})
    return out


def content_tokens(query, stop):
    toks = []
    for w in norm(query).split():
        if w in stop or len(w) < 2 or w in toks:
            continue
        toks.append(w)
    return toks


def looks_portuguese(query, pt_en):
    ws = norm(query).split()
    return any(c in query.lower() for c in "áàâãéêíóôõúç") or any(w in PT_DISTINCT or w in pt_en for w in ws)


def token_cooccurrence(query, refs, stop, pt_en, en_pt):
    """(tokens, full, partial): BODY excerpts of the summaries with ALL the tokens (or at least 60%, minimum 2) of the query, each token
    accepted in Portuguese or English, and with at least half of the tokens in the section title or at the start (subject) of the excerpt (a loose mention does not count). Each item = (score, file, excerpt); more tokens at the start/title of the excerpt = better."""
    toks = content_tokens(query, stop)
    if refs is None or len(toks) < 2:
        return toks, [], []
    forms = [word_forms(t, pt_en, en_pt) for t in toks]
    need = max(2, -(-len(toks) * 3 // 5))
    full, part = [], []
    for fn, chunks in refs["files"].items():
        for c in chunks:
            if c["k"] != "b":
                continue
            words = set((c["t"] + " " + c.get("hn", "")).split())
            n = sum(1 for f in forms if f & words)
            if n < need:
                continue
            lead = set((c.get("l", "") + " " + c.get("hn", "")).split())
            nl = sum(1 for f in forms if f & lead)
            if nl < -(-len(toks) // 2):        # the excerpt must be ABOUT the subject: half of the tokens in the section title or at the start of the excerpt
                continue
            score = n + 0.25 * nl
            (full if n == len(toks) else part).append((score, fn, c))
    full.sort(key=lambda x: (-x[0], x[1], x[2]["x"]))
    part.sort(key=lambda x: (-x[0], x[1], x[2]["x"]))
    return toks, full, part


def term_index_or(query, terms, stop, pt_en):
    """source term index with the PT->EN translated tokens and OR fallback: per source, the pages where the LARGEST number of
    distinct tokens co-occurs (minimum 2). Returns (tokens, {sigla: {pages, n}})."""
    toks = []
    for w in content_tokens(query, stop):
        for cand in [w] + pt_en.get(w, []):
            for t in tokens_of(cand):
                if t not in STOP and t not in toks:
                    toks.append(t)
    result = {}
    for sig, src in terms["sources"].items():
        counts = {}
        for t in toks:
            if t in src["terms"]:
                for p in expand(src["terms"][t]):
                    counts[p] = counts.get(p, 0) + 1
        if not counts:
            continue
        mx = max(counts.values())
        if mx >= 2:
            result[sig] = {"pages": sorted(p for p, c in counts.items() if c == mx), "generic_only": False, "n_terms": mx}
    return toks, result


def covering_topics(sig, pages, data):
    """curated topics (COVERED) whose page ranges contain any of the given pages."""
    hits = {}
    for t in data["topics"]:
        if t.get("level", "coberto") != "coberto" or sig not in t["pages"]:
            continue
        rng = parse_pages(t["pages"][sig])
        n = sum(1 for p in pages if any(a <= p <= b for a, b in rng))
        if n:
            hits[t["id"]] = n
    return hits


def topic_dict(t):
    return {"id": t["id"], "title": t["title"], "pages": t["pages"], "ref": t.get("ref"), "summary": t.get("summary"),
            "level": t.get("level", "coberto"), "note": t.get("note")}


def print_topic(r, show_summary=True):
    print("-" * 60)
    print("ID: %s" % r["id"])
    print("Title: %s" % r["title"])
    if show_summary and r.get("summary"):
        print("Summary: %s" % r["summary"])
    print("Pages: %s" % fmt_pages(r["pages"]))
    if r.get("ref"):
        print("Reference: references/%s" % r["ref"])


def lookup(query, data, terms, refs):
    """returns a structured dict with level, topics, matches, pointer_topics, outside, term_hits."""
    q = norm(query)
    res = {"query": query, "level": None, "topics": [], "matches": [], "pointer_matches": [], "unverified_topics": [], "pointer_topics": [],
           "outside": [], "related": [], "term_hits": {}, "tokens": [], "covered_by": {}, "pt_query": False, "content_tokens": [],
           "token_matches": [], "by_cooccurrence": None, "translated_tokens": [], "pref_pages": {}}
    body, ptr = search_refs(q, refs, query)
    # round 11: among the excerpts in which the term is the subject, the one that STARTS with the term (or whose section title is the term) comes first
    # ("HOT" before "13.6 TRUNCATE em hot standby"); file order is kept within each group (stable sort)
    strong = sorted([(fn, c) for fn, c in body if is_subject(c, q)], key=lambda it: 0 if starts_with_term(it[1], q) else 1)
    weak = [(fn, c) for fn, c in body if not is_subject(c, q)]
    res["aliases"] = []
    seen = {(fn, id(c)) for fn, c in body} | {(fn, id(c)) for fn, c in ptr}
    alias_terms = []
    for g, others in alias_groups(q, data):
        for t in others:
            if t not in alias_terms:
                alias_terms.append(t)
                ab, ap = search_refs(t, refs, t)
                a_strong = [(fn, c) for fn, c in ab if is_subject(c, t) and (fn, id(c)) not in seen]
                a_weak = [(fn, c) for fn, c in ab if not is_subject(c, t) and (fn, id(c)) not in seen]
                a_ptr = [(fn, c) for fn, c in ap if (fn, id(c)) not in seen]
                for fn, c in a_strong + a_weak + a_ptr:
                    seen.add((fn, id(c)))
                if a_strong or a_weak or a_ptr:
                    ent = next((a for a in res["aliases"] if a["group"] == g["id"]), None)
                    if ent is None:
                        ent = {"terms": [], "equivalent_to": query, "group": g["id"], "validated_pages": g.get("pages", {}), "note": g.get("note", ""), "subject_hits": 0}
                        res["aliases"].append(ent)
                    ent["terms"].append(t)
                    ent["subject_hits"] += len(a_strong)
                strong += a_strong
                weak += a_weak
                body += a_strong + a_weak
                ptr += a_ptr
    res["outside"] = search_curated_outside(q, data)
    by_id = {t["id"]: t for t in data["topics"]}
    for o in res["outside"]:
        for rid in o.get("related", []):
            if rid in by_id:
                res["related"].append(topic_dict(by_id[rid]))
    ptr_topics = pointer_topics_for(q, data)
    for t in alias_terms:
        for pt in pointer_topics_for(t, data):
            if pt not in ptr_topics:
                ptr_topics.append(pt)
    res["pointer_topics"] = [topic_dict(t) for t in ptr_topics]
    res["pointer_matches"] = [{"ref": fn, "section": c["h"], "pages": c["pg"], "text": c["x"]} for fn, c in ptr[:MAX_SNIPPETS]]
    if strong:
        topics, _score = rank_topics(strong, data, q)
        res["topics"] = [topic_dict(t) for t in topics]
        res["matches"] = [{"ref": fn, "section": c["h"], "pages": c["pg"], "text": c["x"]} for fn, c in (strong + weak)[:MAX_SNIPPETS]]
        res["n_matches"] = len(body)
        res["n_subject"] = len(strong)
    res["passing_mentions"] = [{"ref": fn, "section": c["h"], "pages": c["pg"], "text": c["x"]} for fn, c in weak[:MAX_SNIPPETS]] if not strong else []
    res["n_passing"] = len(weak) if not strong else 0
    exact_out = any(norm(o["term"]) == q for o in res["outside"])
    if exact_out or (res["outside"] and not body and not ptr_topics):
        res["level"] = LEVEL_SEM
    elif strong:
        res["level"] = LEVEL_COBERTO
    elif weak or ptr_topics or ptr:
        res["level"] = LEVEL_PONTEIRO
    else:
        toks, hits = term_index_search(query, terms)
        res["tokens"] = toks
        res["term_hits"] = hits
        for sig, info in hits.items():
            if info["pages"]:
                res["covered_by"][sig] = covering_topics(sig, info["pages"], data)
        if any(info["pages"] or info["generic_only"] for info in hits.values()):
            res["level"] = LEVEL_PONTEIRO
        else:
            res["level"] = LEVEL_SEM
    if res["level"] == LEVEL_PONTEIRO and not res["tokens"]:
        toks, hits = term_index_search(query, terms)
        res["tokens"] = toks
        res["term_hits"] = hits
        for sig, info in hits.items():
            if info["pages"]:
                res["covered_by"][sig] = covering_topics(sig, info["pages"], data)
    # round 9: the whole phrase is in no summary; try tokens (Portuguese or compound query), co-occurrence and OR fallback
    if res["level"] != LEVEL_COBERTO and not res["outside"] and not strong and not ptr and not ptr_topics:
        stop, pt_en, en_pt = lang_cfg(data)
        pt = looks_portuguese(query, pt_en)
        res["pt_query"] = pt
        toks, full, part = token_cooccurrence(query, refs, stop, pt_en, en_pt)
        res["content_tokens"] = toks
        pick = full or part
        if pick:
            res["token_matches"] = [{"ref": fn, "section": c["h"], "pages": c["pg"], "text": c["x"]} for _s, fn, c in pick[:MAX_SNIPPETS]]
            res["n_matches"] = res["n_subject"] = len(pick)
            res["by_cooccurrence"] = "all" if full else "partial"
            topics, _score = rank_topics([(fn, c) for _s, fn, c in pick], data)
            res["topics"] = [topic_dict(t) for t in topics]
            res["matches"] = res["token_matches"]
            # round 11: STRONG co-occurrence = all the tokens already appear in the section title/subject of the excerpt. The level stays POINTER ONLY when
            # the phrase is not exact (invariant: an out-of-order phrase is never COVERED), but the text makes clear that a summary EXISTS and shows the topic and the page.
            strict = bool(full) and full[0][0] >= len(toks) * 1.25 - 1e-9
            res["strict_cooccurrence"] = strict
            res["level"] = LEVEL_COBERTO if (full and pt) else LEVEL_PONTEIRO
        elif res["level"] == LEVEL_SEM and pt:
            ttoks, thits = term_index_or(query, terms, stop, pt_en)
            res["translated_tokens"] = ttoks
            if thits:
                res["tokens"], res["term_hits"], res["level"] = ttoks, thits, LEVEL_PONTEIRO
                for sig, info in thits.items():
                    res["covered_by"][sig] = covering_topics(sig, info["pages"], data)
    if res["level"] == LEVEL_PONTEIRO and res["term_hits"]:
        res["pref_pages"] = preferred_pages(res, refs, data)
    return res


def preferred_pages(res, refs, data):
    """round 11: sorts the pages of the source term index. Among the pages where the terms co-occur, first come those that a BODY excerpt
    of the summaries cites and that talks about the terms (at least half of them; extra weight if they are in the section title or the excerpt subject), because that is where the
    package has already checked the content; the others stay in numeric order. Returns {sigla: [sorted pages]}."""
    out = {}
    toks = res.get("tokens") or []
    if refs is None or not toks or not res.get("term_hits"):
        return out
    _stop, pt_en, en_pt = lang_cfg(data)
    forms = [word_forms(t, pt_en, en_pt) for t in toks]
    need = max(1, -(-len(toks) // 2))
    for sig, info in res["term_hits"].items():
        pages = info.get("pages") or []
        if not pages:
            continue
        hit, score = set(pages), {}
        for fn, chunks in refs["files"].items():
            for c in chunks:
                if c["k"] != "b" or sig not in c["pg"]:
                    continue
                words = set((c["t"] + " " + c.get("hn", "")).split())
                n = sum(1 for f in forms if f & words)
                if n < need:
                    continue
                lead = set((c.get("l", "") + " " + c.get("hn", "")).split())
                nl = sum(1 for f in forms if f & lead)
                w = n + 1.5 * nl
                for a, b in parse_pages(c["pg"][sig]):
                    for p in range(a, b + 1):
                        if p in hit and w > score.get(p, 0):
                            score[p] = w
        if score:
            sup = sorted(score, key=lambda p: (-score[p], p))
            out[sig] = {"order": sup + [p for p in pages if p not in score], "supported": sup}
    return out


def first_page_hint(res):
    """the first page the lookup returned (summary excerpt, pointer topic or term index), for the agent to read instead of guessing a page.
    Round 11: a summary excerpt only counts if it matched ALL the terms; otherwise, the term-index pages that a package summary cites
    and that talk about the terms (res['pref_pages']) take precedence, and only then the first numeric page of the index."""
    toks = res.get("content_tokens") or []
    full = res.get("by_cooccurrence") == "all"
    for m in (res.get("token_matches") if full else None) or res.get("passing_mentions") or []:
        if m.get("pages"):
            return "; ".join("%s %s" % kv for kv in m["pages"].items())
    for sig, pp in (res.get("pref_pages") or {}).items():
        if pp["supported"]:
            return "%s p.%d (a page that a package summary cites and that talks about the terms)" % (sig, pp["supported"][0])
    for r in res.get("pointer_topics") or []:
        if r.get("pages"):
            return fmt_pages(r["pages"])
    for m in res.get("token_matches") or []:
        if m.get("pages"):
            return "; ".join("%s %s" % kv for kv in m["pages"].items())
    for sig, info in res.get("term_hits", {}).items():
        if info.get("pages"):
            return "%s %s" % (sig, compress(info["pages"][:3]).split(", ")[0])
    return None


def print_aliases(res):
    for a in res.get("aliases", []):
        pg = "; ".join("%s %s" % kv for kv in a.get("validated_pages", {}).items())
        print("PT/EN equivalence applied: '%s' = %s%s. %s" % (a["equivalent_to"], " / ".join("'%s'" % t for t in a["terms"]),
                                                                " (validated on %s)" % pg if pg else "", a.get("note", "")))


def render(res):
    q = res["query"]
    for n in res["outside"]:
        print("NOT IN THE SOURCE: '%s' - %s" % (n["term"], n["note"]))
    lvl = res["level"]
    if lvl == LEVEL_COBERTO and res.get("by_cooccurrence"):
        print("LEVEL: COVERED - query read word by word (without function words; Portuguese <-> English): the terms '%s' co-occur in %d summary excerpt(s) "
              "of the package (references/*.md). It is not an exact phrase: check whether the excerpt answers the question and cite its page."
              % (" + ".join(res["content_tokens"]), res.get("n_matches", 0)))
        for m in res["matches"]:
            pg = " (%s)" % "; ".join("%s %s" % kv for kv in m["pages"].items()) if m["pages"] else ""
            print("  - %s > %s%s: %s" % (m["ref"], m["section"], pg, m["text"]))
        if res["topics"]:
            print("Curated topics linked to these excerpts (pages and summary):")
            for r in res["topics"]:
                print_topic(r)
    elif lvl == LEVEL_COBERTO:
        print("LEVEL: COVERED - the term '%s' is the subject of %d summary excerpt(s) of the package (references/*.md) (%d mention the term in total):"
              % (q, res.get("n_subject", 0), res.get("n_matches", 0)))
        print_aliases(res)
        for m in res["matches"]:
            pg = " (%s)" % "; ".join("%s %s" % kv for kv in m["pages"].items()) if m["pages"] else ""
            print("  - %s > %s%s: %s" % (m["ref"], m["section"], pg, m["text"]))
        if res["topics"]:
            print("Curated topics linked to these excerpts (pages and summary):")
            for r in res["topics"]:
                print_topic(r)
        else:
            print("No curated topic is linked to these excerpts by pages; use the excerpts and the indicated reference.")
        if res["pointer_topics"]:
            print("\nThere is also POINTER ONLY content (no summary in the package):")
            for r in res["pointer_topics"]:
                print_topic(r, show_summary=False)
                print("Note: %s" % r["note"])
    elif lvl == LEVEL_PONTEIRO:
        if res.get("strict_cooccurrence") and res.get("token_matches"):
            print("LEVEL: POINTER ONLY (inexact phrase) - there is content in the sources for '%s' and the package HAS a likely summary: all the terms appear in the "
                  "title/subject of the excerpt below." % q)
            print("Action: read the excerpt and the page it cites (check it in the PDF), answer with what the page says and cite that page; "
                  "if the excerpt does not answer the question, say the package has no summary and suggest reading the page.")
        else:
            print("LEVEL: POINTER ONLY - there is content in the sources for '%s', but the package has NO summary of it." % q)
            print("Action: tell the user there is content on the indicated pages (no summary in the package) and suggest reading it; "
                  "do NOT say the book does not cover the subject and do not state the content without reading the page.")
        print_aliases(res)
        for r in res["pointer_topics"]:
            print_topic(r, show_summary=False)
            print("Note: %s" % r["note"])
        if res.get("token_matches"):
            print("Summary excerpts that best match the words of the query (%s; co-occurrence %s; check whether they answer the question):"
                  % (" + ".join(res["content_tokens"]), res["by_cooccurrence"]))
            for m in res["token_matches"]:
                pg = " (%s)" % "; ".join("%s %s" % kv for kv in m["pages"].items()) if m["pages"] else ""
                print("  - %s > %s%s: %s" % (m["ref"], m["section"], pg, m["text"]))
            if res.get("strict_cooccurrence") and res["topics"]:
                print("Curated topics linked to these excerpts (pages and summary):")
                for r in res["topics"]:
                    print_topic(r)
        if res.get("translated_tokens"):
            print("Portuguese query translated for the source index: %s" % ", ".join(res["translated_tokens"]))
        if res.get("n_passing"):
            print("The term appears only IN PASSING in %d summary excerpt(s) (it is the subject of none; use with care, check whether the excerpt answers the question):" % res["n_passing"])
            for m in res["passing_mentions"]:
                pg = " (%s)" % "; ".join("%s %s" % kv for kv in m["pages"].items()) if m["pages"] else ""
                print("  - %s > %s%s: %s" % (m["ref"], m["section"], pg, m["text"]))
        for m in res["pointer_matches"]:
            print("The term appears only in pointer/map text: %s > %s: %s" % (m["ref"], m["section"], m["text"]))
        if res["tokens"]:
            print("Terms searched in the term index: %s" % ", ".join(res["tokens"]))
        for sig, info in res["term_hits"].items():
            if info["generic_only"]:
                print("%s: term too frequent in this source (does not discriminate pages); refine the query." % sig)
                continue
            pg = info["pages"]
            ppref = (res.get("pref_pages") or {}).get(sig)
            pref = ppref["order"] if ppref else None
            if pref:
                pg = pref
                shown = ", ".join("p.%d" % p for p in pg[:12])
            else:
                shown = compress(pg[:30])
            more = " ... (+%d pages)" % (len(pg) - (12 if pref else 30)) if len(pg) > (12 if pref else 30) else ""
            co = " (co-occurrence of all the terms)" if len(res["tokens"]) > 1 else ""
            print("%s: occurrences on %d page(s)%s: %s%s" % (sig, len(pg), co, shown, more))
            cb = res["covered_by"].get(sig) or {}
            if cb and ppref and ppref["supported"]:
                print("   pages that a package summary cites and that talk about the terms: %s (curated topics: %s); the other pages in this list are textual occurrence only"
                      % (", ".join("p.%d" % p for p in ppref["supported"][:8]), ", ".join(sorted(cb))))
            elif cb:
                print("   pages that fall within curated topics: %s (the summaries of those topics do NOT cite the term)" % ", ".join(sorted(cb)))
        print("This is a textual occurrence (no semantics): the page may only mention the term.")
        hint = first_page_hint(res)
        if hint:
            print("PAGE TO READ FIRST: %s (the first one the index returned; read it before answering, do not use another page from memory)." % hint)
    else:
        if res["outside"]:
            print("LEVEL: NOT COVERED - '%s' is on the curated list of subjects OUTSIDE the package sources. Say that the package sources do not cover it "
                  "or answer labeling it [extrapolation]." % q)
            for r in res["related"]:
                print("Related (partial coverage in the package):")
                print_topic(r)
        else:
            print("LEVEL: NOT COVERED - no occurrence of '%s' in the term index of the sources (terms searched: %s)." % (q, ", ".join(res["tokens"]) or "none"))
            print("Attention: this does NOT prove that the sources do not cover the topic; the sources are in English and the index is textual. "
                  "Try English synonyms. If there is still no result, say 'I did not find it in the package sources' and label the rest [extrapolation].")
            if res.get("pt_query"):
                print("The query looks like Portuguese: do NOT conclude absence. Try the English equivalent (source terms, e.g.: transaction, "
                      "procedure, lock, partition, time zone) and query again; the lookup already tried to translate the known words.")


def main():
    ap = argparse.ArgumentParser(description="Three-level lookup (COVERED / POINTER ONLY / NOT COVERED) with verified PDF pages")
    ap.add_argument("query", nargs="?", help="term to search for")
    ap.add_argument("--topic", help="term to search for (alternative to the positional argument)")
    ap.add_argument("--list", action="store_true", help="list all indexed topics")
    ap.add_argument("--json", action="store_true", help="structured JSON output")
    a = ap.parse_args()
    data = load_json(INDEX_PATH)
    if not a.json:
        print("Convention: pages = PDF. " + data["_meta"]["page_convention"])
    if a.list:
        print("Total indexed topics: %d" % len(data["topics"]))
        for t in data["topics"]:
            tag = "COVERED" if t.get("level", "coberto") == "coberto" else "POINTER ONLY"
            print("- %s [%s]: %s [%s]" % (t["id"], tag, t["title"], fmt_pages(t["pages"])))
        return 0
    q = a.topic or a.query
    if not q:
        ap.print_help()
        return 2
    terms = load_json(TERMS_PATH) if os.path.exists(TERMS_PATH) else {"sources": {}}
    refs = load_refs()
    res = lookup(q, data, terms, refs)
    if a.json:
        print(json.dumps(res, ensure_ascii=False, indent=1))
    else:
        render(res)
    return EXIT[res["level"]]


if __name__ == "__main__":
    sys.exit(main())
